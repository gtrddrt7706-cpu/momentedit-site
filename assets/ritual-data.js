/* 어조 문안 하나를 꺼낸다. **없으면 null** — 부르는 쪽은 null 이면 현행을 쓴다.
   ★null 을 빈 문자열로 바꾸지 말 것. 빈 문자열은 「말이 없다」가 되어 그 순간이 통째로 조용해진다. */
function TONE_NAR(group, key, tone) {
  if (!tone) return null;
  var g = TONE[group]; if (!g) return null;
  var e = g[key]; if (!e) return null;
  return e[tone] || null;
}

