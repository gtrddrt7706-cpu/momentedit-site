function courseLines(full) {
  /* ★★[OPEN_COURSE 2026-09-25 설계 명세 1 · 8장] 고객은 이제 코스를 고르지 않는다 — 순간만 담는다.
     ★전부 assets/ritual-open.js 에서 뽑는다. 카드 문구·판·예시·시간을 여기 손으로 적으면 화면과 갈린다.
     ★«추천»이라 말하지 않는다 — 현장 검증 전이라 «예시»다(사장님 9/25). */
  const out = [], nm = (k) => O.CARDS[k].n;
  out.push('- 두 분은 코스를 고르지 않고 예식에 담을 순간만 고른다. 빈 채로 시작하고, 입장과 닫는 인사는 늘 있다(하객 맞이 안내도 늘 나간다).');
  out.push('- 순서는 저희가 맞춰 둔 한 줄이고 두 분이 바꾸지 않는다: ' + O.ORDER.filter((k) => k !== 'guest').map(nm).join(' → ') + ' → 닫는 인사.');
  out.push('- 무엇을 담아도 값은 같다. 담을수록 본식이 길어지고 사진과 인사가 줄어든다(둘을 더해 ' + O.DAYMIN + '분 · 하루 140분은 그대로).');
  if (full) {
    O.PICKABLE.forEach((k) => {
      const c = O.CARDS[k], chips = (k === 'toast' ? ['toast', 'wine'] : (O.CHIPS[k] ? [k] : [])).map((x) => O.CHIPS[x].map((y) => y[1]).join(' / '));
      out.push(`  · ${c.n}: ${c.one} (누가 · ${c.who})${chips.length ? ' · 고를 판: ' + chips.join(' · ') : ''}`);
    });
    out.push('  · 화촉에 서실 분: ' + O.CANDLE_WHO.map((c) => c[1]).join(' / ') + '(연출 단계에서 고른다)');
  }
  out.push('- 예시 넷(«추천»이 아니라 «예시» — 누르면 그 순간들이 담기고, 그다음 더하고 빼면 된다):');
  O.EXAMPLES.forEach((ex) => {
    const T = O.applyExample({}, ex.k), sp = O.span(T);
    out.push(`  · ‹${ex.nm}› ${ex.title}: ${O.ORDER.filter((k) => !O.ALWAYS[k] && T.on[k]).map((k) => O.CARDS[k].sn).join(' · ')} · 본식 ${sp.body} · 사진과 인사 ${sp.photo}`);
  });
  out.push('- 노래: 축가 순서는 폐지됐고 라이브 노래는 받지 않는다. 영상 속 노래와 가족의 깜짝 축하는 괜찮다 — 「두 사람이 준비한 순서」에 넣는다(3분 안).');   // [SONG_RETIRED] 사장님 결정 1(2026-09-25)
  out.push('- 와인: 따로 순서가 없다. 축배 안에서 두 분이 두 와인을 한 잔에 붓는다(또는 양가가 한 병씩 · 붓지 않음).');   // [WINE_RETIRED] 와인 세리머니 순서는 2026-08-16 폐지 · 붓기는 축배 안(사장님 결정 2 · 2026-09-25)
  out.push('- 옛 코스(이름으로 고르던 방식)로 이미 만든 식순은 그대로 유지된다. 그 이름을 먼저 꺼내 권하지 않는다.');
  return out.join('\n');
}

