// 마지막 줄을 착지시킨다 — 선언을 뺐으면 «종결 장치»를 대신 넣어야 한다 [LETTER_LAND]
//
//   node scripts/apply-letter-landing.mjs [--write]
//
// ★왜 — 2026-09-11 사장님: *"최선인지 검토 요즘인스타감성 멋진 감동 등등의 다양한게 멋진멘트들인지"*
//   앞 커밋에서 선언을 전부 뺐더니 편지가 «흐지부지» 끝났다. 조사 둘로 원인이 특정됐다.
//
// ★★[원인 1] 「평생 사랑하겠습니다」가 하던 일은 약속이 아니라 «종결 신호»였다.
//   Smith, Poetic Closure(1968)의 고전적 종결 장치 목록에 「단서 없는 단언」이 들어 있다.
//   선언을 뺀 것은 의미상 옳았지만, 구조상 종결 장치를 통째로 뺀 것이었다.
//   대체재는 «다른 선언»이 아니라 «다른 종류의 종결 신호»여야 한다.
//   Smith 의 핵심 원리가 그대로 처방이 된다 — «패턴을 세워 두고 마지막에 깨면 그 자리가 끝으로 읽힌다».
//
// ★★[원인 2] 「-더라」는 턴을 넘기는 어미다.
//   국어학에서 '-더-'는 «직접 지각 + 의외성»을 함께 나르고, 그 화행은 «보고»다.
//   보고는 청자의 반응을 부르므로 구조적으로 말차례를 넘긴다 — 그래서 읽는 사람이 「그래서?」 하고 기다렸다.
//   게다가 서술어가 「되다」였다. 추상 동사라 심상 부호화가 0이다(Paivio 이중부호화 ·
//   구체어 회상률이 추상어의 약 두 배).
//
// ★★[처방] -더라가 넘긴 턴을 «사물·행동 한 줄»이 받아서 닫는다.
//   ①마지막 줄은 앞줄보다 짧게(10음절 안팎) — 길이가 줄어드는 것 자체가 끝 신호다.
//   ②마지막은 «미래의 사소한 행동» 또는 «현재의 관찰». 백석 「날이 밝으면 또 …가 청배를 팔러 올 것이다」형.
//     Baxter 「Against Epiphanies」(1997)가 상품화된 통찰의 대안으로 꼽은 «완결되지 않은 행동»이다.
//   ③선언을 꼭 지워야 하는 건 아니다 — «가운데»로 옮기면 된다.
//     윤동주 「서시」는 「사랑해야지」를 중간에 두고 마지막은 「오늘 밤에도 별이 바람에 스치운다」로 닫는다.
//     마지막에 있으면 서약이지만 중간에 있으면 그냥 말한 것이 된다.
//   ④앞에 나온 사물을 마지막에 되불러온다(recapitulatio) — 새 약속을 더하지 않고 닫는 법.
//   ⑤대상을 바꾼다. 나태주 「풀꽃」이 「너도 그렇다」로 화살을 듣는 사람에게 돌리는 그 자리.
//
// ★「인스타 감성」을 목표로 삼지 않는다 — 그 말은 문체 이름이 아니라 평가어이고,
//   조롱하는 변형이 「갬성」이다. 목표는 «저장되는 문장»의 형식 조건으로 바꿔 잡았다.
//
// ★감성팔이가 시작되는 지점 셋을 피한다: ①근거 없는 포괄 보증 ②아무에게나 맞는 말
//   ③파는 사람이 사는 사람의 감정을 대신 말할 때(「이 순간 두 분은 벅차오릅니다」). 셋째가 제일 위험하다.
//
// ★[VOW_ECHO] 신랑 「괜찮다고 해도 한 번은 더 물어볼게」 ↔ 신부 「너는 나한테만 먼저 말해」.
//   서로 맞물리게 두었다. 한쪽만 고치지 말 것.
//
// ★종료 코드 0 다 맞음 · 1 자리를 못 찾음
