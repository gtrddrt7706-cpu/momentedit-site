//
//   node scripts/apply-letter-formal.mjs [--write]
//
// ★왜 — 2026-09-11 사장님: *"조금더 격식을 차리는듯한 멘트로 개선"*
//   앞 판은 오글거림을 피하려다 «구어»로 너무 내려갔다. 하객 앞에서 소리 내어 읽는 글인데
//   문자메시지처럼 읽혔다. 조사도 같은 말을 했다 — 업계가 「하객 연령대가 다양하므로 격식체」를
//   가르치고, 창작 코퍼스 12/12가 -습니다체였다.
//
// ★★[격식을 올리되 상투로 돌아가지 않는다] 이게 이 수정의 전부다.
//   격식 = 닳은 말이 아니다. 올리는 방법은 «어휘를 고급스럽게»가 아니라 셋뿐이다:
//     ①구어 축약을 편다 — 「그거」→「그걸」, 「말 안 해」→「말하지 않아」, 「-더라고요」→「-더군요」
//     ②조사를 복원한다 — 「너 만나고」→「너를 만나고」, 「이 사람이랑」→「이 사람과」
//     ③군말을 뺀다 — 「그냥」·「좀」·「되게」·「진짜로요」
//   ★새 미사여구를 넣지 않는다. 넣는 순간 LETTER_REAL 이 지운 업체 샘플로 되돌아간다.
//
// ★★[말단계는 그대로 둔다] 격식을 올린다고 말단계를 바꾸지 않는다.
//   서로에게 하는 서약·편지는 반말이 맞다 — 존대로 바꾸면 «둘 사이»가 사라지고 낭독 대회가 된다.
//   부모님께 드리는 말만 -습니다체로 올렸고, 어머님이 사위에게 하는 말은 -요체로 둔다
//   (장모가 사위에게 -습니다체를 쓰면 도로 어색하고, 하게체는 낭독 대본에 위험하다).
//
// ★★[고백의 흐린 말끝은 건드리지 않는다] 「아직도 마음이 그래」·「저 하나도 버거운데」.
//   여기를 정제하면 LETTER_COST 가 죽는다. 못 끝낸 문장이 감동의 장치다.
//
// ★[한 곳만 바꿔 말을 키웠다] 신랑 헌정의 「전화 자주 하겠습니다. 진짜로요.」 →
//   「자주 찾아뵙겠습니다.」 격식이 오르면서 약속도 커진다. 웃음 한 스푼은 잃었지만
//   부모님께 드리는 마지막 말이 농담으로 닫히던 문제가 함께 해결된다.
//
// ★종료 코드 0 다 맞음 · 1 자리를 못 찾음
