const lines = fs.readFileSync(CAST, 'utf8').split('\n');
// 각 [NN] 머리 아래 «빈 줄 전까지»가 그 클립의 대사다
const at = new Map();
lines.forEach((l, i) => { const m = /^\[(\d+)\]/.exec(l); if (m) at.set(m[1], i); });

let bad = 0;
const plan = [];
for (const [no, text, from] of NEW) {
  const h = at.get(no);
  if (h === undefined) { console.log(`✗ [${no}] 머리를 못 찾았다`); bad++; continue; }
  let e = h + 1;
  while (e < lines.length && lines[e].trim()) e++;
  const old = lines.slice(h + 1, e);
  const neu = text.split('\n').map((s) => s.trim()).filter(Boolean);
  plan.push({ no, h, e, old, neu, from, head: lines[h] });
  console.log(`  [${no}] ${lines[h].split('·')[1]?.trim() ?? ''}  ${old.length} → ${neu.length}문장   (${from})`);
}
if (bad) { console.log('\n자리를 못 찾은 것이 있다 — 아무것도 쓰지 않는다.'); process.exit(1); }

if (!WRITE) { console.log('\n(안 씀 · --write 로 실제 반영)'); process.exit(0); }
const out = [];
let i = 0;
for (const p of plan.sort((a, b) => a.h - b.h)) {
  out.push(...lines.slice(i, p.h + 1), ...p.neu);
  i = p.e;
}
out.push(...lines.slice(i));
fs.writeFileSync(CAST, out.join('\n'));
console.log(`\n반영함 · ${plan.length}클립`);
// [REDUB_COST] 이미 받은 목소리 중 다시 받아야 할 것
console.log('\n★이미 받은 소리 중 다시 받을 것 (문장이 바뀐 클립):');
for (const p of plan) if (p.old.join('\n') !== p.neu.join('\n')) console.log(`   ${p.head.split('→')[1]?.trim() ?? p.no}`);
