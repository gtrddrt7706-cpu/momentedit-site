import fs from 'node:fs';

const ROOT = new URL('..', import.meta.url).pathname;
const P = (f) => ROOT + f;
const before = new Map();
const read = (f) => { if (!before.has(f)) before.set(f, fs.readFileSync(P(f), 'utf8')); return before.get(f); };
const now = new Map();
const cur = (f) => now.has(f) ? now.get(f) : read(f);

let bad = 0;
/* ★한 자리라도 어긋나면 아무것도 쓰지 않는다(앞 판과 같은 규약 — 절반만 반영된 대본이 제일 나쁘다). */
function sub(f, old, neo, want = 1) {
  const s = cur(f);
  const n = s.split(old).length - 1;
  if (n !== want) { console.log(`  ✗ ${f}: "${old.slice(0, 34)}…" ${n}건 (${want} 기대)`); bad++; return; }
  now.set(f, s.split(old).join(neo));
  console.log(`  ✓ ${f}: ${want}건`);
}
