/* [CANT_LOOK] 0=통과 1=틀림 — 갇힌 고객이 «관리자 눈에» 보이는가 [STRANDED_QUEUE]
 *
 * ★왜 만드나 (2026-08-17 사용자 실제 고립)
 *   강제변경으로 되돌린 고객이 «계약완료 + 입금 확인»으로 갇혔는데
 *   관리자 「처리할 일」은 **0건**이었고, 진행 현황엔 «입금 대기»로 보였다(돈은 이미 받았는데).
 *   고객 화면은 «디렉터가 확인하는 중»이라 기다리라 했다 — **서로 기다리는 교착.**
 *   문(단계 맞추기 버튼)은 상세에 있었지만, 홈에서 그 고객으로 들어갈 이유가 없었다.
 *   ★«문을 만드는 것»과 «그 문으로 데려가는 것»은 다른 일이다. 이 검사는 뒤쪽을 지킨다.
 *
 * ★진짜 adminHome() 을 돌려 큐와 파이프라인 부제를 실측한다(코드 읽기 아님).
 * ★가짜 경보도 같이 막는다 — 중도금을 미리 낸 정상 고객이 걸리면 큐가 늑대소년이 된다.
 *
 * 사용: node scripts/audit/stranded-queue.mjs
 */
import { openWorld, kstAgo } from './_gasworld.mjs';

const { G, world } = openWorld();
const old = kstAgo(24 * 23);
let fail = 0;
const ok = (c, m, d) => { console.log(`  ${c ? '✅' : '❌'} ${m}${c || !d ? '' : '\n       ' + d}`); if (!c) fail++; };

const BASE = { 개인코드: 'ME-TEST', 신랑이름: '희준', 신부이름: '미쿠', 연락처: '010-0000-0000', 이메일: 't@e.com',
  상품타입: '시그니처', 계약상태: '서명완료', 계약서명일시: old, 계약서발송일시: old, 계약총액: 2500000,
  예식일: '2026-10-28', 입금자명: '정희준', 확인일시: old, 신청일시: old,
  /* 영수증은 «발행됨»으로 둔다 — 미발행이면 현금영수증 카드가 큐를 채워 «0건이 아니다»가 되어
     이 검사가 무엇을 보고 있는지 흐려진다. 사용자 실제 상황도 발행 뒤였다(그래서 0건이었다). */
  동의기록: JSON.stringify({ 계약: { at: old }, 영수증기준일: { 예약금: old },
    영수증발행: { 예약금: { 번호: '1' }, 계약금: { 번호: '2' } } }), 처리이력: '' };
const BK = { 개인코드: 'ME-TEST', 상태: '확정', 선택날짜: '2026-09-01', 선택시간: '14:50', 토큰: 'tk', 입금확인: '확인' };

const CASES = [
  /* [라벨, 덮어쓸 셀, 밀림으로 잡혀야 하나] */
  ['계약완료 + 계약금 확인 (사용자 실제 고립)', { 현재단계: '계약완료', 입금상태: '확인' }, true],
  ['계약완료 + 중도금·잔금까지 확인', { 현재단계: '계약완료', 입금상태: '확인', 중도금상태: '확인', 잔금상태: '확인' }, true],
  ['상담완료로 더 내려간 채 입금 확인', { 현재단계: '상담완료', 입금상태: '확인' }, true],
  ['스냅 촬영확정 + 입금 확인', { 현재단계: '촬영확정', 상품타입: '웨딩스냅', 계약총액: 1200000, 입금상태: '확인' }, true],
  /* ↓ 가짜 경보가 나면 안 되는 자리 — 여기가 붉어지면 규칙이 너무 넓다 */
  ['정상 · 입금완료 단계', { 현재단계: '입금완료', 입금상태: '확인' }, false],
  ['정상 · 입금완료인데 중도금을 미리 냄', { 현재단계: '입금완료', 입금상태: '확인', 중도금상태: '확인' }, false],
  ['정상 · 제작중인데 잔금을 미리 냄', { 현재단계: '제작중', 입금상태: '확인', 중도금상태: '확인', 잔금상태: '확인' }, false],
  ['정상 · 계약완료 · 입금 대기', { 현재단계: '계약완료', 입금상태: '대기' }, false],
  ['정상 · 예외 단계(취소)는 건드리지 않는다', { 현재단계: '취소', 입금상태: '확인' }, false],
];

console.log('[갇힌 고객이 「처리할 일」에 뜨는가 · 가짜 경보는 없는가]');
for (const [label, over, want] of CASES) {
  world(Object.assign({}, BASE, over), Object.assign({}, BK));
  let h; try { h = G.adminHome(); } catch (e) { ok(false, `${label} · adminHome 실행`, e.message); continue; }
  const q = (h.queue.urgent || []).concat(h.queue.normal || []);
  const hit = q.filter((x) => x.kind === '단계밀림');
  ok(!!hit.length === want, `${label} — 단계밀림 ${want ? '떠야 한다' : '뜨면 안 된다'}`,
    hit.length ? hit[0].sub : ('큐 ' + q.length + '건: ' + q.map((x) => x.kind).join(', ')));
  if (hit.length) ok(/단계 맞추기/.test(hit[0].sub), `${label} — 무엇을 하라는지 적혀 있다`, hit[0].sub);
}

/* 파이프라인 부제 — «입금 대기»라는 거짓말을 하지 않는가 [SUB_PAID_TRUTH] */
console.log('\n[진행 중 현황 부제가 사실을 말하는가]');
const subOf = (over) => {
  world(Object.assign({}, BASE, over), Object.assign({}, BK));
  const h = G.adminHome();
  const m = JSON.stringify(h.pipeline).match(/"sub":"([^"]*)"/);
  return m ? m[1] : '';
};
const s1 = subOf({ 현재단계: '계약완료', 입금상태: '확인' });
ok(!/^입금 대기$/.test(s1), '입금이 확인된 고객을 «입금 대기»라고 하지 않는다', s1);
ok(/단계 밀림/.test(s1), '대신 «단계 밀림»이라고 이름을 불러 준다', s1);
const s2 = subOf({ 현재단계: '계약완료', 입금상태: '대기' });
ok(s2 === '입금 대기', '진짜 입금 대기는 종전대로 «입금 대기»', s2);

console.log(`\n결과 — ${fail ? '실패 ' + fail + '건' : '실패 0건 (전부 통과)'}`);
process.exit(fail ? 1 : 0);
