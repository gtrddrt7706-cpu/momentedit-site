#!/usr/bin/env python3
# 이어 읽기 [READ_THROUGH] — 2026-09-20
#
# 왜 — 검사 스물다섯 항목이 전부 «문장»과 «짝»만 본다. 그런데 오늘 한 줄로 이어 읽었더니
#   기계가 하나도 못 본 것이 넷 나왔다.
#     ① 26번 「말은 여기서 다 나왔습니다」 — 그 뒤로 진행자가 열 번 더 말한다
#     ② 38번 한 클립에 「인사를 드리」 두 번
#     ③ 58「이어서」 · 76「이어집니다」 — 이음말끼리 같은 말
#     ④ 04a 「맞아 주시면 좋겠습니다」 뒤에 「휴대폰 꺼 주세요」 — 마무리하고 다시 사무
#   ★전부 «흐름»이다. 문장 하나만 보면 다 멀쩡하다.
#   ★그래서 이건 기계가 대신 못 한다. 이 도구는 «읽을 것을 차례대로 세워 주는» 것까지만 한다.
#
#   python3 이어읽기.py
import json, glob

T = {}
for f in sorted(glob.glob('round[0-9].json')):
    for c in json.load(open(f, encoding='utf-8'))['clips']:
        T[c['no']] = (c['slug'], c['voice'], [s['new'] for s in c['sents'] if s['new'].strip()])

# 한 예식을 골라 세운다 — 갈래가 있는 자리는 하나만 고른다.
# ★다른 조합도 읽어야 한다. 갈래를 바꿔 가며 몇 번 읽는 것이 이 도구를 쓰는 법이다.
#
# ★★[2026-09-20 둘째 판] 그 말을 적어 놓고 한 조합만 읽고 끝냈다. 갈래를 바꿔 다시 읽었더니
#   넷이 더 나왔다 — 전부 «안내 성우판에서 고친 것을 부부 목소리판에 안 옮긴» 자리다.
#   그래서 조합을 손으로 고르지 않고 이름으로 세워 둔다. 하나만 읽고 끝내지 못하게.
#     python3 이어읽기.py            ← 다섯 조합 전부
#     python3 이어읽기.py 부부목소리   ← 하나만
BR = {
 '기본':       {'맞이': ['01a','02a','03a','04a','84'], '입장': ['05','52'],
                '선언': ['30'],                         '축배': ['40','56'], '케이크': ['41','77']},
 '부부목소리': {'맞이': ['01c','02c','03c','04c','84'], '입장': ['05','52'],
                '선언': ['30'],                         '축배': ['40','56'], '케이크': ['41','77']},
 '가족선언':   {'맞이': ['01a','02a','03a','04a','84'], '입장': ['05','52'],
                '선언': ['21','32','57'],               '축배': ['40','56'], '케이크': ['41','77']},
 '하객서약':   {'맞이': ['01a','02a','03a','04a','84'], '입장': ['05','52'],
                '선언': ['33','34','35'],               '축배': ['40','56'], '케이크': ['41','77']},
 '1인칭입장':  {'맞이': ['01c','02c','03c','04c','84'], '입장': ['22c','52'],
                '선언': ['31'],                         '축배': ['42','76','56','77'], '케이크': []},
}
def seq(b):
    return [('하객 맞이', b['맞이']), ('온라인 맞이', ['48']), ('입장', b['입장']),
            ('첫인사', ['11','06w','07w','12']), ('서약', ['13','14']), ('반지', ['15','16']),
            ('편지', ['27','20']), ('덕담', ['22','24']), ('헌정', ['38','39']),
            ('성혼선언', b['선언']), ('자유 순서', ['58','59']),
            ('축배', b['축배']), ('케이크', b['케이크']),
            ('사진', ['26','60','65']), ('인사 돌기', ['61','62']),
            ('마지막 한 장', ['63','64']), ('배웅', ['44','45','85','47'])]

import sys
want = [a for a in sys.argv[1:] if a in BR] or list(BR)
print('이어 읽기 — 한 예식을 차례대로. **소리 내어 읽으십시오.**')
print('찾는 것: 앞뒤가 어긋나는 말 · 같은 일을 두 번 시키는 것 · 약속해 놓고 안 지키는 것 ·')
print('         마무리한 뒤에 다시 사무로 돌아가는 것 · 진행자가 자기 말을 부정하는 것')
print('★한 조합만 읽고 끝내지 마십시오. 넷은 갈래를 바꾸고 나서야 나왔습니다.\n')
for _b in want:
  print('\n' + '█' * 46); print(f'█  갈래 조합 — {_b}'); print('█' * 46 + '\n')
  for sec, nos in seq(BR[_b]):
    if not nos: continue
    print(f'━━ {sec} ' + '━' * max(0, 40 - len(sec) * 2))
    for no in nos:
        if no not in T: print(f'   [{no}] (이 회차에 없음)'); continue
        sl, v, ss = T[no]
        print(f'  [{no}] {sl} · {v}')
        for s_ in ss: print(f'      {s_}')
    print()
