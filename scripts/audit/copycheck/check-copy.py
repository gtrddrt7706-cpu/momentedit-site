    #     아니라 «빠짐없이 차례로»라는 관용이다. 뒤에 씩/도/한 이 붙으면 수량 단정이 아니다.
    #   ★[오탐 교정 2026-09-20 · 스물여덟 번째] 「한 분 한 분」이 그래도 걸렸다.
    #     열아홉 번째 교정이 «뒤에 한 이 붙으면 빼기»였는데, 그러면 **앞의 「한 분」만 빠지고
    #     뒤의 「한 분」이 걸린다**(뒤에는 「이」가 붙으니까). 관용구는 조각으로 보면 안 된다 —
    #     한 덩어리로 가리고 나서 센다.
