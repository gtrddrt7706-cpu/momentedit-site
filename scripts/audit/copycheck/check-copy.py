#   ★배타 갈래마다 따로 센다. 한 예식에서 귀에 닿는 것이 그 예식의 분포다.
ASK_END = {
    '~주세요':          r'주세요[.!?]?$',
    '~주시기 바랍니다':  r'주시기 바랍니다[.!?]?$',
    '~주시면 됩니다':    r'(주시면|하시면|드리면) 됩니다[.!?]?$',
    '~부탁드립니다':     r'부탁드립니다[.!?]?$',
    '~주십시오':        r'(주십시오|하십시오|십시오)[.!?]?$',
    '~좋겠습니다':      r'좋겠습니다[.!?]?$',
}
def _askkind(x):
    for k, rx in ASK_END.items():
        if re.search(rx, x.strip()): return k
    return None
