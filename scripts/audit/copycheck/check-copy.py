    m = re.search(r'(한|세|네|다섯)\s*(통|명|분|개)(?![도씩]|\s*한)|(한)\s*장(?!도)(?=\s*(을|에|이|은)?\s*(더|씩))|(두)\s*(통|명|개|장)', t)
    if m: R('수량 단정', no, i, f'「{m.group(0)}」 — 예식마다 달라질 수 있습니다')

