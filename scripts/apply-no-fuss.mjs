//     「듣다가 울컥하셔도 괜찮습니다. / 오늘은 그래도 되는 날입니다. / 이제, 그 목소리가 이어집니다.」
//   근거는 「25명 방에는 익명이 없어 우는 사람을 전부가 본다 · 기쁨이라 이름 붙여 주지 않으면
//   누가 힘든가 보다로 읽힌다」였다. 그 관찰 자체는 틀리지 않았지만 처방이 틀렸다 —
//   ★감정을 «허용»한다는 것이 곧 «예고»다. 아직 아무 일도 안 일어났는데 나레이션이 먼저
