//   감정에 이름을 붙이지 않고, 무엇을 느낄지 말하지 않고, 두 사람을 실제보다 크게 말하지 않는다.
//   하객에게 줄 것이 있다면 «느낌»이 아니라 «할 일»이다(그대로 들으시면 된다).
//   ★이 원칙은 편지 한 자리에만 적용한 것이 아니다 — 감동 구간 전체를 이 눈으로 다시 본다.
//
// ★재녹음: 3클립(편지 여는 말 세 갈래 · 한 예식에 하나만 나간다).

import fs from 'node:fs';
const ROOT = new URL('..', import.meta.url).pathname;
const now = new Map();
const cur = (f) => now.has(f) ? now.get(f) : fs.readFileSync(ROOT + f, 'utf8');
let bad = 0;
const sub = (f, o, n, want = 1) => {
  const s = cur(f), c = s.split(o).length - 1;
  if (c !== want) { console.log(`  ✗ ${f}: "${o.slice(0, 30)}…" ${c}건 (${want} 기대)`); bad++; return; }
  now.set(f, s.split(o).join(n)); console.log(`  ✓ ${f} ${want}건`);
};
const DATA = 'assets/ritual-data.js', OP = 'order-preview.html';

/* 부모님께 — 「앞자리에 계신다」는 사실 하나, 「지금 읽는다」는 동작 하나. 그게 전부다.
   ★「세상에서 가장 먼저 사랑해 준」을 버렸다. 사실이긴 하지만 나레이터가 할 말은 아니다 —
     그 말은 편지 안에서 딸이 하면 되고, 실제로 하고 있다(「낳아주셔서, 키워주셔서, 참아주셔서」). */
sub(DATA, '세상에서 가장 먼저 두 사람을 사랑해 준 분들이, 오늘 앞자리에 앉아 계십니다. 듣다가 울컥하셔도 괜찮습니다. 오늘은 그래도 되는 날입니다. 이제, 그 목소리가 이어집니다.',
          '앞자리에 부모님이 계십니다. 두 사람이 쓴 편지를, 지금 직접 읽습니다.');
sub(OP,   '세상에서 가장 먼저 두 사람을 사랑해 준 분들이, 오늘 앞자리에 앉아 계십니다. 듣다가 울컥하셔도 괜찮습니다. 오늘은 그래도 되는 날입니다. 이제, 그 목소리가 이어집니다.',
          '앞자리에 부모님이 계십니다. 두 사람이 쓴 편지를, 지금 직접 읽습니다.');

/* 서로에게 — 「오래 담아 둔 마음을 꺼냅니다」도 감정을 대신 말하는 문장이다.
   무엇을 담아 뒀는지는 편지가 말한다. 여는 말은 «편지가 있다»와 «지금 읽는다»만 말한다. */
sub(DATA, '이제, 두 사람이 서로에게 오래 담아 둔 마음을 꺼냅니다. 듣다가 울컥하셔도 괜찮습니다. 오늘은 그래도 되는 날입니다. 이제, 그 목소리가 이어집니다.',
          '두 사람이 서로에게 쓴 편지가 있습니다. 지금 직접 읽습니다.');
sub(OP,   '이제, 두 사람이 서로에게 오래 담아 둔 마음을 꺼냅니다. 듣다가 울컥하셔도 괜찮습니다. 오늘은 그래도 되는 날입니다. 이제, 그 목소리가 이어집니다.',
          '두 사람이 서로에게 쓴 편지가 있습니다. 지금 직접 읽습니다.');

/* 둘 다 — 편지가 «두 통»이라는 사실이 이 갈래의 전부다. 세어 주면 하객이 길이를 가늠한다. */
sub(DATA, '세상에서 가장 먼저 두 사람을 사랑해 준 분들이 앞자리에 계시고, 이제 서로의 평생이 될 두 사람이 여기 섰습니다. 오늘, 그 모든 마음을 차례로 소리 내어 전합니다. 듣다가 울컥하셔도 괜찮습니다. 오늘은 그래도 되는 날입니다. 이제, 그 목소리가 이어집니다.',
          '두 사람이 편지를 두 통 썼습니다. 부모님께 한 통, 서로에게 한 통입니다. 차례로 읽습니다.');
sub(OP,   '세상에서 가장 먼저 두 사람을 사랑해 준 분들이 앞자리에 계시고, 이제 서로의 평생이 될 두 사람이 여기 섰습니다. 오늘, 그 모든 마음을 차례로 소리 내어 전합니다. 듣다가 울컥하셔도 괜찮습니다. 오늘은 그래도 되는 날입니다. 이제, 그 목소리가 이어집니다.',
          '두 사람이 편지를 두 통 썼습니다. 부모님께 한 통, 서로에게 한 통입니다. 차례로 읽습니다.');

if (bad) { console.log(`\n★${bad}자리 어긋나 아무것도 쓰지 않았다.`); process.exit(2); }
for (const [f, s] of now) fs.writeFileSync(ROOT + f, s);
console.log('\n[NO_FUSS] 편지 여는 말 세 갈래 반영.');
