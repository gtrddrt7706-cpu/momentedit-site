// 상충은 풀어 놨는데 «너무 늦게» 도착했다 [CHAR_LAND]
//
// 사장님 「이거 상충된다고 얘기했었는데 반영이안된거야? 누락이야?」
//        「참는성격이라는데 따지는성격이라고하잖아」
//
// ★반영은 돼 있었다(03d66eee [CHAR_ONE]). 누락이 아니다. 그런데 사장님 귀에는 안 잡혔다.
//   그러면 «고친 게 약한 것»이다. 무엇이 약했는지 줄 번호로 보면 분명하다:
//
//     165  나는 따지는 사람이야.                            ← 여기서 «성격 딱지»가 붙는다
//     166  작년에 내가 너한테 삼십 분을 따진 날이 있었어.
//     167  너는 다 듣고 나서 밥 먹었냐고 물었어.
//     168  그때 좀 졌다고 생각했어.
//     169  너한테는 삼십 분을 따지면서, 정작 내가 힘든 건…   ← 해소가 «네 줄 뒤»에 온다
//
//   소리는 되감기가 없다. 네 줄(약 20초) 동안 하객은 「따지는 사람」이라는 딱지를 들고 있고,
//   그 앞 순서에서 신랑이 「한 번도 힘들다는 말을 안 했어 · 몇 번을 혼자 참았을지」라고
//   말해 둔 참이다. 20초는 모순을 견디기에 너무 길다.
//
// ★그래서 두 군데를 고친다. 없던 말을 만들지 않고, 이미 있는 뜻을 «제때·같은 말»로 옮긴다.
//
//   ① 딱지를 그 자리에서 «한정»한다.
//      「나는 따지는 사람이야」는 성격 전체를 말하는 문장이다. 그런데 실제로 이 인물이 하는 것은
//      «너에 대해서는 할 말을 다 하고, 자기 힘든 것은 안 말하는» 것이다. 앞 절반만 딱지로 붙어 있었다.
//      → 「나는 너한테 할 말은 다 하는 사람이야.」
//        성격이 아니라 «너에게 하는 행동»이 된다. 뒤에 나오는 「삼십 분을 따진 날」·「앞으로도
//        나는 따질 거야」는 그대로 산다 — 따지는 장면은 남기고 «딱지»만 걷는 것이다.
//
//   ② 해소 문장이 신랑의 말을 «같은 단어로» 받게 한다.
//      신랑: 「너는 나한테 **한 번도 힘들다는 말**을 안 했어.」
//      신부: 「정작 내가 **힘든 건 한 마디도** 안 하더라.」   ← 뜻은 같은데 말이 다르다
//      귀는 같은 말이 다시 나올 때만 «아, 그 얘기»라고 잇는다. 표현을 바꾸면 연결이 안 들린다.
//      → 「정작 내가 힘들다는 말은 한 번도 안 했더라.」
//        신랑이 쓴 「힘들다는 말」·「한 번도」를 그대로 되받는다. 20분 전 문장이 여기서 닫힌다.
//
// ★「정작」은 그대로 둔다 — 뒷절 주어가 「너」로 들리던 것을 잡아 주는 말이다([TONE_POLISH] ④).
// ★재녹음: 1클립(09_vow-bride).

import fs from 'node:fs';
const ROOT = new URL('..', import.meta.url).pathname;
const F = ROOT + 'docs/plans/식순연구/배역_예시_대사.txt';
let s = fs.readFileSync(F, 'utf8');
let bad = 0;
const sub = (o, n) => {
  const c = s.split(o).length - 1;
  if (c !== 1) { console.log(`  ✗ "${o.slice(0, 30)}…" ${c}건 (1 기대)`); bad++; return; }
  s = s.replace(o, n); console.log(`  ✓ ${n}`);
};
sub('나는 따지는 사람이야.', '나는 너한테 할 말은 다 하는 사람이야.');
sub('정작 내가 힘든 건 한 마디도 안 하더라.', '정작 내가 힘들다는 말은 한 번도 안 했더라.');
if (bad) { console.log('\n★어긋나서 아무것도 쓰지 않았다.'); process.exit(2); }
fs.writeFileSync(F, s);
console.log('\n[CHAR_LAND] 신부 서약 2줄 반영.');
