//   전문가가 쓴 매끄러운 추도사보다 아는 사람이 더듬으며 한 것이 선호됐다.
//   ★문안을 대신 써 주는 우리에게 이건 경고다 — 너무 잘 쓰면 진다.
//
// ★★[근거 3 — 편지를 쓰게 된 과정을 편지 안에서 말한다]
//   실물 편지 10건 중 3건이 그렇게 했고(「사실 이거 일주일 전에 미리 써 뒀어」),
