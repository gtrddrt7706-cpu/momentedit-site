// ★다섯 각도로 각각 새로 쓰고 안마다 세 심사자가 점수를 냈다. 「한 장면」 안이 8.0/10 으로 1위였고
//   (셋 다 8점), 그 위에 심사자들이 공통으로 짚은 여섯 곳을 내가 고쳤다.
//
// ═══ 옛 글이 왜 약했나 (내가 짚은 것 + 심사에서 확인된 것) ═══
//   ①메타로 연다 — 「이거 쓰는 데 한 달 걸렸다 / 길게는 안 한다」. 그래 놓고 17줄이라 약속을 안 지킨다.
//     게다가 어머님이 「오늘 할 말을 적어 왔습니다」로 여는 자리와 겹친다.
//   ②「말로 하는 사람 / 그냥 하는 사람」을 「앞쪽 / 뒤쪽」으로 받는다. 무엇이 앞이고 뒤인지 청자가
//     역산해야 한다. 소리는 되감기가 없다.
//   ③조언 덩어리 넉 줄(미운 날 · 먼저 말 걸기 · 지는 게 아니다 · 오래 걸렸다). 넷이 붙으면 훈화다.
//   ④**딸을 보내는 아버지의 말인데 딸 이야기가 두 줄**이고 그것도 맨 끝이다. 사위 이야기가 중심이었다.
//   ⑤진짜 정점(「스물아홉 해 잡고 걸었다 / 그게 참 좋았다」)이 맨 끝에 눌린 뒤
//     「잘 살아라」라는 가장 상투적인 말이 붙어 여운을 깎는다.
//   ⑥「아버지는 …」 자칭 두 번, 둘 다 「알았다」로 끝나 같은 모양이 반복된다.
//
// ═══ 새 글이 하는 일 ═══
//   ★장면 하나(정류장 마중)로 끝까지 민다. 보일러는 «사위가 한 일»이라, 그걸 중심에 두면
//     아버지가 자기 딸을 두 줄만 말하게 된다. 정류장은 아버지와 딸이 여러 해 반복한 일이라
//     딸이 저절로 중심에 온다.
//   ★일반론을 한 줄도 쓰지 않는다. 「말로 하는 사람이 있고」를 지우고, 대신 아버지 본인이
//     «그냥 하는 사람»인 것을 행동으로 보여 준다 — 버스 시간을 알면서 삼십 분 일찍 나가고,
//     장갑을 하나 더 챙기면서 말은 안 한다. 사위가 어느 쪽인지는 청자가 알아서 안다.
//   ★장갑이 세 번 나온다: 하나 더 챙겼다 → 하윤이는 늘 맨손으로 내렸다 → 그날은 꺼내지 않았다.
//     딸을 건네는 일이 소품 하나로 끝난다. 감정을 한 글자도 말하지 않는다.
//   ★「앞쪽/뒤쪽」이 문자 그대로의 «자리»로 돌아온다 — 나는 뒤에서 갔다 / 너는 계속 옆에서 가라.
//
// ═══ [PEAK_ONE] 을 어떻게 지켰나 ═══
//   ★감정을 말하는 단어가 하나도 없다. 제일 센 두 줄(「그날은 장갑을 꺼내지 않았다」·「나는 뒤에서 갔다」)이
//     둘 다 아무 감정도 말하지 않는 사실 문장이라 청자가 스스로 채운다.
//     어머님은 반대다 — 「그때 저는 좀 무서웠습니다」·「이 걱정을 내려놓았습니다」로 감정을 직접 말한다.
//     말 안 한 쪽이 먼저, 말하는 쪽이 나중이라 낙차가 어머님 쪽으로 떨어진다.
//   ★모양도 일부러 어긋냈다. 어머님의 끝은 «내려놓음»이다. 그래서 아버님을
//     「이제 안 나가도 되겠다」로 끝내지 않았다 — 같은 모양이 먼저 나오면 어머님이 그 말을
//     두 번째로 하는 사람이 된다. 아버님은 «안 놓는 사람»으로 남긴다.
//   ★착지를 일부러 낮췄다. 제일 센 「너는 계속 옆에서 가라」 뒤에 버스 이야기 두 줄을 붙여
//     내려앉힌다. 마지막에 남는 소리가 작아야 방이 부드러운 채로 어머님에게 넘어간다.
//     옛 글이 정점 뒤에 「잘 살아라」로 «더 큰 말»을 붙인 것과 반대 방향이다.
//
// ═══ [CROSS_ECHO] 를 어떻게 피했나 ═══
//   ★묻다·괜찮다·아프다·힘들다·말 안 하다 계열을 통째로 피했다. 「물었다」까지 「했다」로 낮췄다 —
//     가족 코스에서는 덕담이 서약보다 «먼저» 나오는데(큐 8번 · 서약 10번), 아버님이 그 동사를
//     먼저 써 버리면 뒤따르는 어머님의 「한 번 더 물었지요」가 헌 말이 된다.
//   ★딸이 아픈 걸 숨긴다는 소재 자체를 안 건드렸다 — 그건 어머님 것이다.
//   ★신부 서약의 「할 말은 다 하는 사람이야」와도 안 부딪히게, 딸을 말하는 쪽/안 하는 쪽
//     어디로도 규정하지 않았다. 이 글에서 딸은 «맨손으로 내리고 걸음이 빠른 사람»일 뿐이다.
//
// ═══ 심사에서 짚힌 여섯 곳을 내가 고쳤다 ═══
//   ①「지난 설에는 둘이 왔다」 → 「지난겨울에는 내리는 사람이 둘이었다」
//     어머님의 「지난여름에 둘이 우리 집에 왔을 때요」와 «시간부사 + 둘이 왔다» 틀이 같았다.
//     두 클립이 마이크만 넘기고 연달아 나가는데 같은 모양으로 꺾으면 어머님 전환이 헌 것이 된다.
//     장갑 때문에 겨울이어야 하므로 계절은 겨울로 두고, 방문 프레임을 버렸다.
//   ②「십 년을 그렇게 말했다」 → 삭제. 신부 편지가 스물넷에 집에 살던 장면을 말하는데(「거실에서
//     두 분 목소리가 늦게까지」) 십 년이면 열아홉에 집을 떠난 것이 되어 어긋난다.
//     ★앞줄 「내릴 때마다」가 이미 반복을 말한다. 요약 줄이라 빼면 셋이 한 번에 풀린다 —
//       연대 충돌 · 「했다」 3연속 · 유일한 설명 줄.
//   ③「금방 왔다고 했다」 → 「나는 금방 왔다고 했다」. 표시 없이 주어가 딸→아버지로 뒤집히던 자리다.
//   ④「버스 시간을 알면서도」와 「몇 시 차인지 알려 줘라」가 부딪혔다(알면서 왜 알려 달라나).
//     → 「다음엔 미리 안 알려 줘도 된다」. 앞줄을 버리는 대신 «이미 안다»를 끝에서 쓴다.
//     ★「말 안 하고 와도 된다」로 쓰려다 되돌렸다 — CROSS_ECHO 의 「말을 안 해」 계열과 낱말이 겹친다.
//   ⑤「서준아, 너는 옆에서 가라」 → 「계속 옆에서 가라」. 이미 손을 잡고 옆에 있는 사람에게
//     옆에 가라고 하면 한 박자 걸린다. 「계속」이 그걸 «지금 하는 것을 계속하라»로 바꾼다.
//   ⑥「겨울에는 장갑을 하나 더 들고 나갔다」 → 「겨울이면 장갑을 하나 더 챙겼다」.
//     앞 두 줄이 있었다/나갔다인데 또 나갔다라 도입부가 단조로웠다.
//   ★「서준이 손을 잡고 있었다」 → 「하윤이가 서준이 손을 잡고 있었다」. 누가 누구 손을 잡았는지
//     소리로는 갈린다. 잡은 쪽이 딸인 편이 이 장면에 맞다 — 고른 것은 딸이다.
//
// ★재녹음: 1클립(12_bless-father · 16줄 → 15줄).
// ★2위는 「짧게」 안(7.2)이었다. 보일러 장면을 살리고 아버지와 딸의 싸움 장면을 앞에 넣은 판인데,
//   「사흘을 서로 말을 안 했다」가 CROSS_ECHO 낱말과 겹치고 「그게 참 좋았다」의 정도부사가 남아 있었다.

import fs from 'node:fs';
const ROOT = new URL('..', import.meta.url).pathname;
const F = ROOT + 'docs/plans/식순연구/배역_예시_대사.txt';
let s = fs.readFileSync(F, 'utf8');

const OLD = `서준아, 하윤아.
이거 쓰는 데 한 달 걸렸다.
그래도 길게는 안 한다.
작년 겨울에 우리 집 보일러가 고장 났다.
날이 추워서 하윤이한테만 말했는데, 그 주 토요일에 서준이가 왔더라.
두 시간을 만지더니 고쳐 놓고, 밥도 안 먹고 갔다.
아버지는 그날 알았다.
말로 하는 사람이 있고, 그냥 하는 사람이 있다.
서준아, 너는 뒤쪽이더라.
하윤아, 너는 앞쪽이지.
살다 보면 서로 미운 날이 온다.
그때 먼저 말을 거는 쪽은 아마 하윤이일 거다.
지는 게 아니다. 아버지는 그걸 알기까지 오래 걸렸다.
하윤이 손을 스물아홉 해 잡고 걸었다.
그게 참 좋았다.
잘 살아라.`;

const NEW = `서준아, 하윤아.
하윤이가 집에 오는 날이면 나는 정류장에 먼저 나가 있었다.
버스 시간을 알면서도 삼십 분씩 일찍 나갔다.
겨울이면 장갑을 하나 더 챙겼다.
하윤이는 늘 맨손으로 내렸다.
내릴 때마다 아빠 언제 왔냐고 했다.
나는 금방 왔다고 했다.
지난겨울에는 내리는 사람이 둘이었다.
하윤이가 서준이 손을 잡고 있었다.
그날은 장갑을 꺼내지 않았다.
집까지 셋이 걸었다.
나는 뒤에서 갔다.
서준아, 너는 계속 옆에서 가라.
하윤아, 다음엔 미리 안 알려 줘도 된다.
나는 그때도 먼저 나가 있을 거다.`;

if (s.split(OLD).length - 1 !== 1) { console.log('✗ 옛 글을 못 찾았다 — 이미 바뀌었거나 원천이 다르다.'); process.exit(2); }
fs.writeFileSync(F, s.replace(OLD, NEW));
const syl = (t) => (t.match(/[가-힣]/g) || []).length;
const lines = NEW.split('\n');
console.log(`[BLESS_SCENE] ${lines.length}줄 · 최장 ${Math.max(...lines.map(syl))}음절 · 총 ${lines.reduce((a, l) => a + syl(l), 0)}음절`);
