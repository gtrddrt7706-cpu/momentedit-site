// 쉼표가 숨 자리를 잘못 잡은 네 곳 [BREATH]
//
//   node scripts/apply-breath.mjs [--write]
//
// ★왜 — 2026-09-12 사장님: *"최종 스킬사용 점검개선"*
//   감동 구간 108문장을 스킬 기준으로 다시 재니 risk_band=low 이고 번역투 계열은 전부 0이었다
//   (이중 피동 0 · by-피동 0 · 대명사 밀도 0 · 무생물 주어 0.0 · 한자 명사화 0).
//   ★무생물 주어 0.0 은 [TIC_CUT] 에서 의인화 추상 주어를 걷어낸 것이 수치로 나온 것이다.
//   임계를 넘는 지표는 «하나»뿐이었다 — ending_comma_rate 0.150 (z=+1.39).
//
// ★★[쉼표를 «줄이는» 일이 아니다 — 위치를 고치는 일이다]
//   같은 검사가 comma_usage_rate 를 z=-1.21 로 찍는다. 쉼표 «수»는 오히려 적다.
//   그러니 전부 지우면 과교정이다. 낭독에서 쉼표는 숨 자리라, 대부분은 있어야 한다.
//   문제는 «연결어미 뒤 + 앞 토막이 짧을 때»다 — 한 호흡이어야 할 자리에서 멈추게 된다.
//   30개를 전수로 재서 그 조건에 맞는 넷만 골랐다. 나머지 26개는 손대지 않는다:
//     호격 뒤(「하윤아,」) · 3연 병렬(「낳아주셔서, 키워주셔서, 참아주셔서」) ·
//     감탄 도입(「자, 다 같이」) · 주제 제시(「그 사진, 엄마가 찍은 거야」) ·
//     앞 토막이 11음절 넘는 연결어미(숨이 필요한 길이다)
//
// ★★[대구는 «살린다» — 지울 뻔했다]
//   「~고 나서,」가 셋이라 반복으로 보였는데, 그중 둘은 신부 서약 안의 의도된 대구였다:
//     너는 다 듣고 나서 밥 먹었냐고 물었어.          ← 그가 한 일
//     대신 다 따지고 나서 내가 먼저 밥 먹었냐고 물을게.  ← 내가 따라 하겠다는 약속
//   형태가 같은 것이 장치다. 하나를 다른 말로 바꾸면 약속이 안 보인다.
//   ★그래서 문형은 그대로 두고 쉼표만 뺐다. 한 호흡으로 붙으니 대구가 오히려 선명해진다.
//   ★셋 중 남은 하나([11])는 대구 밖이라 그 자리만 형태가 겹쳤다 — 거기도 쉼표만 뺀다.
//
// ★[10] 「밥 먹다가,」는 앞 토막이 13음절인데도 골랐다. 길이가 아니라 «의미»가 끊긴다 —
//   「밥 먹다가」에서 멈추면 아버지가 밥을 먹다 만 것처럼 들리고, 정작 한 말이 뒤로 밀린다.
//   이 편지에서 아버지가 허락하는 단 한 문장이다. 두 동강 내지 않는다.
//
// ★종료 코드 0 다 맞음 · 1 자리를 못 찾음
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const WRITE = process.argv.includes('--write');
const CAST = path.join(ROOT, 'docs/plans/식순연구/배역_예시_대사.txt');

const EDIT = [
  ['[09] 대구 앞쪽 · 앞토막 7음절',
   '너는 다 듣고 나서, 밥 먹었냐고 물었어.',
   '너는 다 듣고 나서 밥 먹었냐고 물었어.'],
  ['[09] 대구 뒤쪽 · 앞토막 8음절',
   '대신 다 따지고 나서, 내가 먼저 밥 먹었냐고 물을게.',
   '대신 다 따지고 나서 내가 먼저 밥 먹었냐고 물을게.'],
  ['[11] 대구 밖인데 형태만 겹침 · 6음절',
   '다 끝나고 나서, 오늘 고생했다고 그러더라.',
   '다 끝나고 나서 오늘 고생했다고 그러더라.'],
  ['[10] 길이가 아니라 의미가 끊긴다',
   '다음 날 아침에 아빠가 밥 먹다가, 해 보라고 하셨어요.',
   '다음 날 아침에 아빠가 밥 먹다가 해 보라고 하셨어요.'],
];

let s = fs.readFileSync(CAST, 'utf8');
let bad = 0;
for (const [why, from] of EDIT) {
  const n = s.split(from).length - 1;
  console.log(`  ${n === 1 ? '·' : '✗'} ${why.padEnd(32)} ${n}곳`);
  if (n !== 1) bad++;
}
/* ★자가검사 — 지키기로 한 것이 그대로인지 센다. 쉼표를 줄이다 장치를 지우면 안 된다. */
for (const [why, keep] of [
  ['대구 문형 둘', ['다 듣고 나서 밥 먹었냐고', '다 따지고 나서 내가 먼저 밥 먹었냐고']],
  ['3연 병렬', ['낳아주셔서, 키워주셔서, 참아주셔서']],
  ['호격 쉼표', ['하윤아, 서준아.', '서준아, 하윤아.']],
]) {
  const after = EDIT.reduce((a, [, f, t]) => a.split(f).join(t), s);
  const ok = keep.every((k) => after.includes(k));
  console.log(`  ${ok ? '·' : '✗'} ${why} 보존`);
  if (!ok) bad++;
}
if (bad) { console.log('\n맞지 않는 것이 있다 — 아무것도 쓰지 않는다.'); process.exit(1); }
if (!WRITE) { console.log('\n(안 씀 · --write 로 실제 반영)'); process.exit(0); }
for (const [, from, to] of EDIT) s = s.split(from).join(to);
fs.writeFileSync(CAST, s);
console.log(`\n반영함 · ${EDIT.length}곳 (쉼표만 · 낱말은 그대로)`);
