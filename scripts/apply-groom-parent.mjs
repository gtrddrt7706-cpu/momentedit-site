// 신랑 부모가 받기만 하고 있었다 [GROOM_PARENT]
//
//   node scripts/apply-groom-parent.mjs [--write]
//
// ★왜 — 2026-09-12 사장님 결정 ④:
//   *"양가부모 적절하게 추천 신랑부모가 줄수잇는 감동포인트가 잇다면 양쪽 다 준비해서
//     감정이배가될수잇는쪽으로 기획 구현"*
//   지금 덕담은 아버님·어머님 «둘 다 신부 쪽»이고(보일러는 장인 · 양호실은 친정 엄마),
//   신랑 부모는 헌정을 «받기만» 한다. 말이 한 마디도 없다.
//
// ★★[네 번째 덕담을 주지 «않았다» — 그게 이 기획의 핵심이다]
//   가장 쉬운 답은 신랑 부모에게 덕담 하나를 더 주는 것인데, 그러면 덕담이 넷이 되어
//   정점이 넷으로 쪼개진다. 고립 효과는 배경이 평평할 때만 작동한다(PEAK_ONE 에서 이미 겪었다).
//   심리 조사도 «정점을 더하는 것»보다 «골을 없애는 것»이 총평을 더 올린다고 했다(Miron-Shatz 2009).
//   ★그래서 자리를 나눴다 — 신부 쪽 부모는 «말하는 자리»(덕담), 신랑 쪽 부모는 «받는 자리»(헌정).
//     받는 쪽이 짧게 한 번 답하면 희소해서 오히려 세다. 네 줄이면 충분하다.
//
// ★★[무엇을 말하게 할 것인가 — 아들의 말을 «받아 뒤집는다»]
//   신랑 헌정(14)의 핵심은 오래된 사진이다:
//     「사진 뒤에 날짜가 적혀 있길래 세어 봤습니다 / 그때 아버지가 지금 제 나이셨습니다 /
//      저는 아직 저 하나도 버거운데 / … 그 얼굴도 버티는 중이었다는 걸 이제 압니다」
//   아들은 사진 «속»을 보고 «추측»한다. 그런데 그 사진에는 찍은 사람이 있다 —
//   프레임 밖에 서 있던 사람이고, 지금 앞자리에 앉아 있고, 아들은 그 사실을 한 번도 말하지 않았다.
//   ★어머니가 「그 사진, 엄마가 찍은 거야」로 열면 장면이 통째로 뒤집힌다:
//     ①아들의 추측이 목격자의 «사실»로 확인된다(Pfeffer 2006 — 자기 자랑보다 제3자 증언이 세다.
//       아버지가 직접 말하면 자랑이 되고, 아내가 말하면 증언이 된다)
//     ②아들이 「저 하나도 버거운데」라고 한 그 무게가 「사흘을 앓았다」로 «숫자»가 붙는다
//     ③「그래도 다음 주에 또 업더라」가 착지 — 감정을 말하지 않고 행동만 말한다
//   ★CROSS_ECHO 의 확장이다. 이 대본에서 제일 센 장치는 문장 하나가 아니라
//     «두 사람이 상의 없이 같은 것을 알아보는 겹침»이고, 여기서는 «아들의 추측 → 어머니의 확인»이다.
//
// ★[신랑 아버지는 말하지 않는다] 사진 이야기의 «대상»이고, 그를 말하는 것은 아내다.
//   본인이 말하면 자랑이 된다. 그리고 말하는 사람이 늘수록 정점이 흩어진다.
//
// ★★[분량이 불균형해 보이지만 «자리»가 다르다]
//   신부 부모 34문장 · 신랑 어머니 4문장. 덕담은 말하는 자리이고 헌정은 받는 자리다.
//   받는 쪽이 길게 말하면 헌정이 덕담으로 변한다 — 그러면 애초에 나눈 의미가 없다.
//
// ★★[비용 — 새 성우 한 명이 필요하다. 사장님이 고르셔야 한다]
//   화자 라벨은 「시어머님」이다. 주하(신부 어머니)를 쓰면 같은 사람으로 들리므로 안 된다.
//   지금 여덟 자리가 전부 차 있어 빌려 쓸 목소리가 없다.
//   ★배정 전까지 생성기가 「보이스 미배정」으로 알려 준다 — 그게 맞다. 조용히 넘어가면 안 된다.
//
// ★번호는 27이다 — «끝에» 붙인다. 중간에 끼우면 뒤 파일이 전부 개명된다(LEAD_OUT 과 같은 이유).
//
// ★종료 코드 0 다 맞음 · 1 자리를 못 찾음
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const WRITE = process.argv.includes('--write');
const CAST = path.join(ROOT, 'docs/plans/식순연구/배역_예시_대사.txt');

const NEW = `
[27] R-tribute-reply · 시어머님 · 헌정 답 → 27_tribute-reply.mp3
서준아.
그 사진, 엄마가 찍은 거야.
너 업고 그러고 나서 아버지가 사흘을 앓았다.
그래도 다음 주에 또 업더라.
`;

let s = fs.readFileSync(CAST, 'utf8');
let bad = 0;
const has = (t) => s.includes(t);
for (const [why, t, want] of [
  ['아들 헌정이 있다(받을 말이 있어야 한다)', '그 얼굴도 버티는 중이었다는 걸 이제 압니다', true],
  ['아들이 사진을 센다', '사진 뒤에 날짜가 적혀 있길래 세어 봤습니다', true],
  ['아들이 값을 치른다', '저는 아직 저 하나도 버거운데', true],
  ['27번이 아직 없다', '[27]', false],
  ['시어머님 라벨이 아직 없다', '시어머님', false],
]) {
  const ok = has(t) === want;
  console.log(`  ${ok ? '·' : '✗'} ${why}`);
  if (!ok) bad++;
}
const maxNo = Math.max(...[...s.matchAll(/^\[(\d+)\]/gm)].map((m) => +m[1]));
console.log(`  ${maxNo === 26 ? '·' : '✗'} 지금 최대 번호 ${maxNo} → 새 클립은 ${maxNo + 1}`);
if (maxNo !== 26) bad++;
if (bad) { console.log('\n전제가 안 맞는다 — 아무것도 쓰지 않는다.'); process.exit(1); }
if (!WRITE) { console.log(`\n새 클립:\n${NEW.trim()}\n\n(안 씀 · --write 로 실제 반영)`); process.exit(0); }
fs.writeFileSync(CAST, s.replace(/\s*$/, '\n') + NEW.trimStart());
console.log('\n반영함 · [27] R-tribute-reply 추가 · 화자 「시어머님」은 성우 미배정이다(사장님이 고르셔야 한다)');
