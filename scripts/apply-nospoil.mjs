// 진행자가 편지를 먼저 읽어 버리고 있었다 [NO_SPOIL] [NO_VERDICT]
//
//   node scripts/apply-nospoil.mjs [--write]
//
// ★왜 — 2026-09-12 사장님: *"특히 흐름상 감동을 주는부분들 신경써서"*
//   흐름 전수점검에서 감동 구간(편지·덕담·헌정)에만 걸리는 결함 종류가 둘 나왔다.
//   둘 다 «나레이션이 배역의 말을 침범»하는 것이고, 대본을 세로로 읽으면 절대 안 보인다 —
//   나레이션과 배역이 다른 파일에 있어서 «이어 붙였을 때»만 드러난다.
//
// ★★[NO_SPOIL — 예고가 본문의 머리와 꼬리를 먼저 먹었다]
//   편지 여는 말(letter.parent)이 이랬다:
//     「한 번도 다 갚지 못한 그 마음에, 두 사람이 오늘 처음으로 소리 내어 답합니다.」
//   그리고 10초 뒤 신부가 읽는다:
//     첫 줄 「스물아홉 해 동안 고맙다는 말을 제대로 한 적이 없어요.」   ← 「처음으로 소리 내어」
//     끝 줄 「다음에 갈 때도 빈손으로 가겠습니다.」                     ← 「다 갚지 못한」
//   한 줄이 편지의 «머리와 꼬리를 동시에» 앞질렀다. 신부가 벼르던 고백을, 진행자가 더 근사한
//   말로 먼저 해 버린다. 하객은 이미 들은 말을 다시 듣게 되고, 편지는 각주로 떨어진다.
//   ★고침은 «빼기»다. 그 한 줄만 지운다 — 앞 줄(부모님이 여기 계시다는 사실)은 선취가 아니라 배경이라 남긴다.
//   ★[안 건드림] letter.each 의 「오래 담아 둔 마음」도 약하게 겹치지만, 그건 «감정»이지
//     신랑 편지의 «사건»(삼 주를 고쳤다)이 아니다. 재녹음 값을 치를 만큼은 아니다.
//
// ★★[NO_VERDICT — 진행자가 하객의 감상을 대신 결론지었다]
//   덕담 마무리(긴 버전)가 이랬다:
//     「오래 지켜봐 오신 마음이, 그 말씀 안에 다 있었습니다. 그 마음이 오늘 이 자리에 함께 남았습니다.」
//   「다」 한 글자가 «더 느낄 것 없다»가 되고, 「남았습니다」가 아직 진행 중인 여운을 완료형으로 봉인한다.
//   ★모범이 바로 옆에 있다 — 짧은 버전 「방금 그 말은, 오늘 이 자리에 있던 사람들만 들었습니다」.
//     사실만 말하고 감정은 하객에게 맡긴다. 같은 구간에 모범과 반면교사가 나란히 있었다.
//   ★이 클립은 «덕담이 3분을 넘겨 디렉터가 끊었을 때» 나간다. 그러니 잘린 것을 덮어야 한다.
//     새 문안은 잘림을 «결함이 아니라 이치»로 바꾼다 — 원래 한 번에 다 말할 수 없는 것이다.
//
// ★★[NO_VERDICT — 헌정 예고가 장르를 잘못 붙였다]
//   「말로 다 못 한 감사를, 오늘 직접 전합니다」라고 예고하는데, 신랑 헌정의 실체는 감사가 아니다.
//   「사진 속 아버지가 지금 제 나이셨습니다 / 저는 아직 저 하나도 버거운데」 — 뒤늦은 발견이고
//   온도는 미안함에 가깝다. 「감사」라고 이름 붙여 놓으면 하객은 감사를 기다리다 빗나간다.
//   ★그리고 헌정은 말이 아니라 «동작»(꽃·큰절·포옹)이 중심이다. 그래서 하객에게 동작을 볼
//     시간을 주는 쪽으로 바꾼다 — 무엇을 느낄지 정해 주지 않는다.
//   ★tribute-out 은 한 문장에 「오늘」이 둘이었다. 문장을 자른다.
//
// ★★[PRED_ECHO — 연속 두 클립이 같은 동사로 끝났다]
//   입장 마무리 「두 사람이 나란히 섰습니다」 → 바로 다음 클립 「두 사람이 자리에 섰습니다」.
//   전 코스 100% 발생. 구절 겹침 검사로는 「나란히」와 「자리에」가 달라 안 잡혔고,
//   서술어로 세는 검사를 만들고 나서야 나왔다(check-echo-inrun.js).
//   ★게다가 순서가 거꾸로였다 — 「첫 인사가 있습니다」로 예고한 «뒤»에 「섰습니다」가 온다.
//   ★그리고 앞 클립이 「잠시, 두 사람만의 시간입니다」로 닫는데 곧바로 하객에게 인사를 시킨다.
//   빼면 셋이 동시에 풀린다. 한 문장으로 줄인다.
//
// ★비용 — 우성 나레이션 4클립이 재녹음 대상에 새로 들어간다(letter.parent 는 이미 대기 중).
//
// ★종료 코드 0 다 맞음 · 1 자리를 못 찾음
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const WRITE = process.argv.includes('--write');
const DATA = path.join(ROOT, 'assets/ritual-data.js');
const PREV = path.join(ROOT, 'order-preview.html');

const EDIT = [
  ['NO_SPOIL · 편지 여는 말',
   '한 번도 다 갚지 못한 그 마음에, 두 사람이 오늘 처음으로 소리 내어 답합니다. ', ''],
  ['NO_VERDICT · 덕담 마무리(길었을 때)',
   '오래 지켜봐 오신 마음이, 그 말씀 안에 다 있었습니다. 그 마음이 오늘 이 자리에 함께 남았습니다.',
   '오래 지켜봐 오신 마음은 한 번에 다 말해지지 않습니다. 나머지는 두 사람이 살면서 듣습니다.'],
  ['NO_VERDICT · 헌정 예고',
   '말로 다 못 한 감사를, 오늘 직접 전합니다. 두 사람이 천천히 다가갑니다.',
   '두 사람이 천천히 다가가는 동안, 그대로 지켜봐 주시면 됩니다.'],
  ['NO_VERDICT · 헌정 마무리',
   '그 사랑이 있어 오늘의 두 사람이 있고, 오늘 두 집안은 서로의 가족이 되었습니다.',
   '그 사랑이 있어 오늘의 두 사람이 있습니다. 그리고 두 집안은 서로의 가족이 되었습니다.'],
  /* ★[NARV_ZERO] 이 문장은 원천에 «두 곳»이다 — NARR.welcome 과 NARV.welcome[0].
     index 0 은 「지금까지 쓰던 문안」이고 따로 녹음하지 않는다(build-tone-dub.mjs 가 0 을 안 뽑는다 ·
     NARR 녹음을 그대로 쓴다). 그래서 둘은 «항상 같아야» 한다 — 한쪽만 고치면 화면 글과 소리가 갈린다.
     ★「0 은 건드리지 말 것」이라는 주석의 뜻은 «다른 글로 갈아치우지 말라»이지 «NARR 과 어긋나게 두라»가
     아니다. 둘을 같이 고치는 것이 그 규칙을 지키는 방법이다. */
  ['PRED_ECHO · 첫인사 여는 말 (NARR + NARV[0])',
   '먼저, 두 사람이 준비한 첫 인사가 있습니다. 두 사람이 자리에 섰습니다.',
   '먼저, 두 사람이 준비한 첫 인사가 있습니다.', 2],
];

let bad = 0;
const files = [['ritual-data.js', DATA], ['order-preview.html', PREV]];
const src = new Map(files.map(([n, p]) => [n, fs.readFileSync(p, 'utf8')]));
for (const [why, from, to, want = 1] of EDIT) {
  const at = files.map(([n]) => [n, src.get(n).split(from).length - 1]);
  const tot = at.reduce((a, [, n]) => a + n, 0);
  const ok = at[0][1] === want;                    // 원천에 정확히 want 곳
  console.log(`  ${ok ? '·' : '✗'} ${why.padEnd(30)} ${at.map(([n, c]) => `${n} ${c}곳`).join(' · ')}`);
  if (!ok) bad++;
  if (tot === 0) bad++;
}
if (bad) { console.log('\n자리를 못 찾았다 — 아무것도 쓰지 않는다.'); process.exit(1); }
if (!WRITE) { console.log('\n(안 씀 · --write 로 실제 반영)'); process.exit(0); }
for (const [n, p] of files) {
  let s = src.get(n);
  for (const [, from, to] of EDIT) s = s.split(from).join(to);
  fs.writeFileSync(p, s);
}
console.log(`\n반영함 · ${EDIT.length}곳 · 원천과 빌더 인라인 사본을 함께 고쳤다(NAR_MIRROR)`);
