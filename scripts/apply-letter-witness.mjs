//   내 조사 에이전트가 프록시에 막혀 못 열던 것을 사장님이 열어 주셨다. 두 가지가 걸렸다.
//
// ★★[1 · 즉시 교체] 신부 서약의 「혼자서도 잘 사는 줄 알았는데, 너를 만나고 아니라는 걸 알았어」
