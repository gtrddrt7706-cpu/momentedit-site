//   그 구조다. 내 문장은 낱말만 다르고 뼈대가 같다.
//   ★★[LETTER_COST] 에서 내가 «값을 치르는 문장»이라고 자신 있게 넣은 자리였다. 잘못 짚었다.
//     값을 치르는 것처럼 보였지만 실은 «닳은 서사»였고, 하객은 세 번째쯤 알아본다.
//   ★되살리지 말 것. 「혼자서도」·「비혼」·「결혼 생각 없었는데」 계열 전부 금지다.
//
//   대신 넣은 것 — 실물 표본이 실제로 하는 것 둘을 합쳤다:
//     ①자기를 낮추는 농담(@gochall/79 신랑 편지가 진지한 어조 사이사이에 쓴 장치)
//     ②결혼생활에서 바라는 현실적인 것(@soyeoninparis/144 신부 편지의 특징)
//   「앞으로도 나는 따질 거야. 그건 못 고쳐.」 — 못 고친다고 먼저 말하는 것이 진짜 값이다.
//   「대신 다 따지고 나서, 내가 먼저 밥 먹었냐고 물을게.」 — 그가 한 행동을 그대로 돌려준다.
//
// ★★[2 · 부탁을 목격담으로] 어머님 덕담의 축이 «조언»이었다.
//   실물 신랑 어머니 축사(@soyuly, 2024년 가을)의 특징이 «조언 대신 믿음과 축복»이었다.
//   그리고 인스티즈 2025-12-19 댓글에는 부모 편지 낭독을 «대놓고 울리려는 연출»로 보고
//   순서에서 뺐다는 의견이 있었다. 우리는 그 순서를 파는 쪽이라 그 혐의를 특히 조심해야 한다.
//   ★그래서 「한 번만 더 물어봐 주세요」(부탁)를 「한 번 더 묻더군요」(목격)로 바꿨다.
//
//   ★★이 교체로 [CROSS_ECHO] 가 훨씬 세졌다. 순서가 이렇게 된다:
//     ①예식 중반 · 신랑 서약   「괜찮다고 해도 한 번은 더 물을게.」   (약속)
//     ②예식 후반 · 어머님 덕담 「서준이는 한 번 더 묻더군요.」        (증언)
//   어머니가 사위의 약속을 «이미 봤다»고 추인한다. 부탁은 앞으로의 일이지만 목격은 이미 있던 일이라,
//   같은 자리에서 훨씬 강하다. ★둘의 순서를 바꾸지 말 것. 증언이 약속보다 먼저 나오면 죽는다.
//
// ★[준비의 무게] 실물 아버지 축사(@toto-new/119)는 «한 달 동안 읽고 녹음하며 고쳤다»고 했다.
//   내 「적어 왔습니다」보다 세다. 아버님 첫 줄에 옮기되 농담으로 받는다 —
//   실물 표본 전부에 웃음이 있었다(어머니 축사의 우산 은유 구간 · 아버지의 말장난 · 신랑의 자기 낮춤).
