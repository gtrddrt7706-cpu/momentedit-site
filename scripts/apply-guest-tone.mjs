/* ★★[GUEST_TONE 2026-09-14 사장님 지시 — 하객 안내 문구 다섯 자리]
 *
 * 사장님이 네 줄에 «왜»를 붙여 주셨다. 그 넷을 읽고 같은 눈으로 한 자리를 더 골랐다.
 * ★편지·서약·덕담은 손대지 않았다 — 사장님 지적은 전부 «하객에게 하는 안내»였고,
 *   그 감정 구간은 이미 여러 판 다듬어 사장님이 받으신 것이다. 결이 다른 곳에 같은 자를 대지 않는다.
 */
import fs from 'node:fs';
const ROOT = new URL('..', import.meta.url).pathname;
const P = (f) => ROOT + f;
const now = new Map();
const cur = (f) => now.has(f) ? now.get(f) : fs.readFileSync(P(f), 'utf8');
let bad = 0;
/* ★한 자리라도 어긋나면 아무것도 쓰지 않는다 — 절반만 반영된 대본이 제일 나쁘다. */
function sub(f, old, neo, want = 1) {
  const s = cur(f); const n = s.split(old).length - 1;
  if (n !== want) { console.log(`  ✗ ${f}: "${old.slice(0, 30)}…" ${n}건 (${want} 기대)`); bad++; return; }
  now.set(f, s.split(old).join(neo)); console.log(`  ✓ ${f}: ${want}건`);
}
const D = 'assets/ritual-data.js', O = 'order-preview.html';

console.log('\n① 「핑거 푸드」 — 사장님: *"뭔가 부자연스러운단어인거같아 어르신들있으니 적절하게 개선"*');
/* 25명 예식의 하객 대부분은 가족이고, 앞자리에 두 집안 어른이 앉는다.
   그분들 귀에 「핑거 푸드」는 뜻이 한 번에 안 온다 — 들리는 순간 «무슨 푸드?»가 된다.
   ★「다과」는 어르신께 익숙하면서 격이 있다. 「간단한」이 핑거 푸드의 «서서 집어 먹는» 성격을 담는다.
   ★★제공 항목 자체는 그대로다 — 계약서·index.html 의 「웰컴 핑거 푸드·와인」은 손대지 않았다.
     바뀐 것은 «그것을 부르는 말»뿐이다. 그 약속을 빼는 것이 아니다. */
sub(D, '한쪽에 핑거 푸드와 음료를 준비해 두었습니다.', '한쪽에 간단한 다과와 음료를 준비해 두었습니다.');
sub(O, '한쪽에 핑거 푸드와 음료를 준비해 두었습니다.', '한쪽에 간단한 다과와 음료를 준비해 두었습니다.');
sub(D, '한쪽에 핑거 푸드와 음료를 준비해 두었어요.', '한쪽에 간단한 다과와 음료를 준비해 두었어요.');
sub(O, '한쪽에 핑거 푸드와 음료를 준비해 두었어요.', '한쪽에 간단한 다과와 음료를 준비해 두었어요.');

console.log('\n② 「천천히 드시다 자리에 앉아」 — 사장님: *"너무 많이먹으면않되우려 입장시간도 타이트해서'
  + ' 돌아다녀도된다는 문구로 인식되면 부산스러움"*');
/* 세 가지가 한 문장에 다 들어 있었다:
     ①「천천히」가 «시간이 넉넉하다»를 말한다 — 십 분 전 안내인데.
     ②「드시다 … 앉아」 순서라 «먹는 것»이 먼저고 «앉는 것»이 뒤다.
     ③ 그래서 자리를 떠서 다과 쪽으로 가는 그림이 먼저 선다.
   ★순서를 뒤집는 것만으로 셋이 함께 풀린다 — 앉는 것이 먼저, 먹는 것은 앉은 채로.
     하객을 움직이게 하지 않으면서 다과를 «없는 것»으로 만들지도 않는다. */
sub(D, '천천히 드시다 자리에 앉아 주시면 됩니다.', '자리에 앉으셔서 편히 드시면 됩니다.', 2);
sub(O, '천천히 드시다 자리에 앉아 주시면 됩니다.', '자리에 앉으셔서 편히 드시면 됩니다.', 2);

console.log('\n③ 「지금 이 문장도 두 사람이 직접 고른 것입니다」 — 사장님: *"부자연스러워 … 고급스럽게 웨딩무드에 맞게"*');
/* 「이 문장」이 걸린다 — 하객은 «문장»을 듣고 있는 것이 아니라 «안내»를 듣고 있다.
   말하는 사람이 제 말을 «문장」이라 부르면 글을 읽는 티가 난다.
   ★「고른」도 약하다. 남이 차려 놓은 것 중에서 «집었다»는 말이다.
     두 사람이 한 일은 고르는 것이 아니라 정하는 것이다 — 「정했습니다」로 간다. */
sub(D, '오늘 순서도, 지금 이 문장도 두 사람이 직접 고른 것입니다.',
       '오늘의 순서도, 지금 들으시는 이 안내도 두 사람이 정한 것입니다.');
sub(O, '오늘 순서도, 지금 이 문장도 두 사람이 직접 고른 것입니다.',
       '오늘의 순서도, 지금 들으시는 이 안내도 두 사람이 정한 것입니다.');
sub(D, '어떤 순서로 진행할지, 어떤 문장으로 안내할지는 저희가 직접 정했어요.',
       '오늘의 순서도, 지금 들으시는 이 안내도 저희가 정했어요.');
sub(O, '어떤 순서로 진행할지, 어떤 문장으로 안내할지는 저희가 직접 정했어요.',
       '오늘의 순서도, 지금 들으시는 이 안내도 저희가 정했어요.');

console.log('\n④ 「휴대폰은 소리만 줄여」 — 사장님: *"꺼달라고 해야지 멘트 무드에맞게 개선"*');
/* ★★여기에 «부딪히는 것»이 하나 있어 그대로 「꺼 주세요」로 쓰지 않았다.
   바로 다음 줄이 「사진은 편히 남기셔도 좋습니다」다([PHOTO_FREE] · 사장님이 정하신 것).
   전원을 끄라고 하면 그 줄이 바로 거짓이 된다 — 한 클립 안에서 두 말을 하게 된다.
   ★그래서 «소리»를 끈다고 말한다. 사장님이 원하신 «꺼 달라»의 분명함은 그대로 살고,
     사진은 그대로 찍으실 수 있다. 「줄여」의 어중간함만 사라진다.
   ★두 분 목소리판의 「진동으로 바꿔」도 같은 이유로 함께 간다 — 진동은 «켜 두라»는 말이다. */
sub(D, '휴대폰은 소리만 줄여 주시면 됩니다.', '휴대폰 소리는 잠시 꺼 주시기 바랍니다.');
sub(O, '휴대폰은 소리만 줄여 주시면 됩니다.', '휴대폰 소리는 잠시 꺼 주시기 바랍니다.');
sub(D, '휴대폰은 진동으로 바꿔 주시면 됩니다.', '휴대폰 소리는 잠시 꺼 주시면 됩니다.');
sub(O, '휴대폰은 진동으로 바꿔 주시면 됩니다.', '휴대폰 소리는 잠시 꺼 주시면 됩니다.');

console.log('\n⑤ 「두 분이 절반쯤 돌았습니다」 — 사장님 지적 넷과 같은 눈으로 내가 고른 자리');
/* 사람을 주어로 「돌았습니다」라고 하면 어르신 귀에 험하게 들릴 여지가 있고,
   무엇을 하고 있는지도 안 말한다(테이블을 도는 것인지, 사진을 찍는 것인지).
   ★바로 다음 줄이 「아직 만나지 못한 자리도 차례로 찾아뵙습니다」다 —
     거기서 쓰는 말(찾아뵙다·인사)로 앞줄을 맞추면 두 줄이 한 장면이 된다. */
