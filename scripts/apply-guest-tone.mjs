if (bad) { console.log(`\n★${bad}자리가 어긋나 아무것도 쓰지 않았다.`); process.exit(2); }
for (const [f, s] of now) fs.writeFileSync(P(f), s);
console.log(`\n[GUEST_TONE] ${now.size}개 파일 반영.`);
