#!/bin/sh
# ★★[GATE_RED 2026-09-12] 게이트 결과를 «빨간 줄만» 모아 마지막에 크게 다시 찍는다.
#
# 왜 만들었나 — 2026-09-12 에 내가 같은 실수를 두 번 했다.
#   ①[NO_OK_FN] 있지도 않은 `ok` 함수를 써서 검사 세 줄이 죽어 있었는데, 출력에서 'FAIL' 만
#     grep 해 보고 「초록」이라고 보고했다.
#   ②그 뒤에도 merge-guard 출력(7,000줄)을 grep 으로 걸러 보고 「FAIL 은 text-audio 하나뿐」이라고
#     보고했다. 실제로는 빨간 줄이 25건이었다. 그중 13건은 «넣은 날부터 빨간» 검사였고,
#     손으로 만든 실청 도구(audio-review.html)가 생성물에 통째로 덮인 사고도 그 안에 섞여 있었다.
#
# 즉 고장은 게이트가 아니라 «읽는 방법»이었다. 게이트는 제 할 일을 했고, 내가 안 봤다.
#   ★그래서 눈에 의존하지 않게 만든다 — 빨간 줄을 «세어서» 맨 끝에 다시 찍는다.
#     7,000줄 끝에 「빨간 줄 0건」이 없으면 초록이라고 말할 수 없다.
#   ★게이트 자체는 건드리지 않았다. 판정 기구(_gate 트랩·GATE_SELFTEST)는 이미 여러 번
#     반증으로 다져 놓은 것이라, 보고용 기능을 그 안에 밀어 넣어 흔들 이유가 없다.
#
# 쓰는 법:  sh scripts/gate.sh        (푸시 전 · merge-guard.sh 대신 이걸 쓴다)
# 종료 코드는 merge-guard 의 것을 그대로 넘긴다 — 자동화가 이걸 써도 판정이 안 바뀐다.

cd "$(dirname "$0")/.." || exit 1

_log=$(mktemp)
sh automation/tests/merge-guard.sh >"$_log" 2>&1
_rc=$?
cat "$_log"

# ★빨간 줄의 생김새는 세 가지뿐이다 — chk 의 'REVERT?', 하위 검사의 'FAIL', '[XXX] FAIL'.
#   앞에 공백이 붙는 줄이 있어 ^[[:space:]]* 를 둔다(실측: STORY_COVER 가 들여쓴다).
_red=$(grep -cE '^[[:space:]]*(REVERT\?|FAIL |\[[A-Z_]+\] FAIL)' "$_log")

echo
echo "════════════════════════════════════════════════════════════"
echo "  빨간 줄 ${_red}건 · 종료코드 ${_rc}"
echo "════════════════════════════════════════════════════════════"
if [ "${_red:-0}" -gt 0 ]; then
  grep -nE '^[[:space:]]*(REVERT\?|FAIL |\[[A-Z_]+\] FAIL)' "$_log" | sed 's/^/  /'
  echo
  echo "  ★위가 전부다. 이 목록 밖의 줄로 «초록»을 말하지 않는다."
fi
rm -f "$_log"
exit $_rc
