#!/bin/sh
# ★★[GATE_RED 2026-09-12] 게이트 결과를 «빨간 줄만» 모아 마지막에 크게 다시 찍는다.
#
# 왜 만들었나 — 2026-09-12 에 내가 같은 실수를 두 번 했다.
#   ①[NO_OK_FN] 있지도 않은 `ok` 함수를 써서 검사 세 줄이 죽어 있었는데, 출력에서 'FAIL' 만
#     grep 해 보고 「초록」이라고 보고했다.
#   ②그 뒤에도 merge-guard 출력(7,000줄)을 grep 으로 걸러 보고 「FAIL 은 text-audio 하나뿐」이라고
#     보고했다. 실제로는 빨간 줄이 25건이었다. 그중 13건은 «넣은 날부터 빨간» 검사였고,
#     손으로 만든 실청 도구(audio-review.html)가 생성물에 통째로 덮인 사고도 그 안에 섞여 있었다.
#
# 즉 고장은 게이트가 아니라 «읽는 방법»이었다. 게이트는 제 할 일을 했고, 내가 안 봤다.
#   ★그래서 눈에 의존하지 않게 만든다 — 빨간 줄을 «세어서» 맨 끝에 다시 찍는다.
#     7,000줄 끝에 「빨간 줄 0건」이 없으면 초록이라고 말할 수 없다.
#   ★게이트 자체는 건드리지 않았다. 판정 기구(_gate 트랩·GATE_SELFTEST)는 이미 여러 번
#     반증으로 다져 놓은 것이라, 보고용 기능을 그 안에 밀어 넣어 흔들 이유가 없다.
#
# 쓰는 법:  sh scripts/gate.sh        (푸시 전 · merge-guard.sh 대신 이걸 쓴다)
# 종료 코드는 merge-guard 의 것을 그대로 넘긴다 — 자동화가 이걸 써도 판정이 안 바뀐다.

cd "$(dirname "$0")/.." || exit 1

_log=$(mktemp)
sh automation/tests/merge-guard.sh >"$_log" 2>&1
_rc=$?
cat "$_log"

# ★빨간 줄의 생김새 — chk 의 'REVERT?', 하위 검사의 'FAIL', '[XXX] FAIL', 그리고 'DRIFT?'.
#   앞에 공백이 붙는 줄이 있어 ^[[:space:]]* 를 둔다(실측: STORY_COVER 가 들여쓴다).
#   ★[GATE_RED_DRIFT 2026-09-14] 'DRIFT?' 를 늦게 넣었다 — check-source-drift 가 fail=1 을 세우는데
#     그 줄만 다른 모양이라 «빨간 줄 0건 · 종료코드 1» 로 두 번 새어 나갔다. 결국 sh -x 로
#     fail=1 이 서는 자리를 찾아야 했다. 세는 목록은 «fail 을 세우는 모든 모양»이어야 한다.
_red=$(grep -cE '^[[:space:]]*(REVERT\?|DRIFT\?|FAIL |\[[A-Z_]+\] FAIL)' "$_log")

echo
echo "════════════════════════════════════════════════════════════"
echo "  빨간 줄 ${_red}건 · 종료코드 ${_rc}"
echo "════════════════════════════════════════════════════════════"
if [ "${_red:-0}" -gt 0 ]; then
  grep -nE '^[[:space:]]*(REVERT\?|DRIFT\?|FAIL |\[[A-Z_]+\] FAIL)' "$_log" | sed 's/^/  /'
  echo
  echo "  ★위가 전부다. 이 목록 밖의 줄로 «초록»을 말하지 않는다."
elif [ "${_rc}" -ne 0 ]; then
  # ★★[GATE_RED_GAP 2026-09-14] «빨간 줄 0건 · 종료코드 1» 이 나왔다. 둘 다 참이었다 —
  #   빨간 줄의 생김새 세 가지(REVERT?·FAIL·[XXX] FAIL)를 안 쓰고 «✗ … / 틀림 1건» 으로
  #   끝내는 하위 검사(build-listen-tone)가 있었기 때문이다. 그 줄은 세어지지 않았고,
  #   요약만 읽으면 «0건인데 왜 1이지» 하고 7,000줄로 되돌아가야 한다 — 이 파일을 만든 이유가
  #   바로 그 되돌아감을 없애려던 것이었다. 세는 규칙을 넓히면 오탐이 늘어 «0건»의 값이 떨어지니,
  #   세지 못한 경우에 한해 **못 센 줄을 그대로 보여 준다.** 판정은 여전히 종료 코드가 한다.
  echo "  ★빨간 줄로 세어지지 않은 실패가 있다 — 아래가 그 줄이다."
  _hint=$(grep -nE '^[[:space:]]*(✗|틀림 [0-9]+건)' "$_log" | tail -20)
  if [ -n "$_hint" ]; then printf '%s\n' "$_hint" | sed 's/^/  /'
  else
    # ★아무 모양에도 안 걸렸다. 여기서 «아마 이것일 것»이라 짐작하지 않는다 — 찾는 법을 적는다.
    echo "  (아는 모양에 하나도 안 걸렸다. fail=1 이 서는 자리를 그대로 찾으려면:"
    echo "     sh -x automation/tests/merge-guard.sh 2>err.log; grep -n -B12 '^+ fail=1' err.log )"
  fi
fi
rm -f "$_log"
exit $_rc
