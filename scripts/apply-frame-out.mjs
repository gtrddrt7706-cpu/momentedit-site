//
// ═══ 무엇이 부딪히나 ═══
//   [14] 신랑  「아버지가 저를 업고 계셨고, 뒤에서 어머니가 웃고 계셨습니다.」   ← 어머니가 «프레임 안»
//              「저는 사진 속 두 분이 원래 어른인 줄 알았습니다.」                ← 다시 못 박는다
//   [27] 시어머님 「그 사진, 엄마가 찍은 거야.」                                   ← 어머니가 «프레임 밖»
//   둘은 같은 큐(tribute-in)의 같은 라이브 창에 14 → 27 순서로 붙어 있어 사이에 아무 말도 안 낀다.
//   하객은 30초 안에 같은 사진에 대한 두 개의 다른 사실을 듣는다. 그 자리가 헌정의 정점이다.
//
// ═══ ★이건 «의도»가 아니라 정반대다 ═══
//   내가 어제 [27]을 만들면서 적은 근거가 이것이다(apply-groom-parent.mjs:23):
//     「그 사진에는 찍은 사람이 있다 — 프레임 밖에 서 있던 사람이고, 지금 앞자리에 앉아 있고,
//      아들은 그 사실을 한 번도 말하지 않았다.」
//   설계는 어머니를 «프레임 밖»으로 전제했는데, 그 전제가 얹힌 [14] 본문(2026-09-11 판)에는
//   이미 어머니가 프레임 «안»에 들어가 있었다. 새 클립의 전제와 기존 문장이 «한 번도 대조되지 않았다».
//   ★사전 점검 다섯 가지를 돌렸는데(아들 헌정이 있나 · 아들이 사진을 세나 …), 정작
//     「어머니가 사진 안에 있나」는 안 봤다. 내가 세운 전제를 내가 확인하지 않은 것이다.
//
// ═══ 어느 쪽을 고치나 ═══
//   ★[14]를 고친다. [27]을 고치면 장면의 «뒤집기»가 통째로 사라지기 때문이다 —
//     아들이 추측한 것을 목격자가 사실로 바꾸는 것이 이 클립의 존재 이유다.
//   ★어머니를 사진에서 «비우면» [27]의 첫마디가 «아들이 몰랐던 사람»을 채우며 장면을 뒤집는다.
//     설계대로 돌아가는 것이지, 새로 만드는 것이 아니다.
//   ★여는 호명 「어머니, 아버지.」는 그대로 둔다 — 두 분 앞에 서 있는 것과 사진 프레임은 다른 층이다.
//     오히려 둘 다 부르고 사진에서는 아버지만 말하는 편이 뒤집기를 더 크게 만든다.
//
// ═══ 두 번째 것 — 축배 순서 ═══
//   다섯 각도가 같은 것을 잡았다. 나레이션이 「제가 위하여, 하면 다 함께 위하여, 하고 답해 주세요.
//   두 사람의 새로운 시작을 위하여!」로 «선창을 끝낸 뒤»에 하객대표 축사가 흐르고,
//   그 축사가 「자, 다 같이 잔 들겠습니다」로 «또» 부른다. 이미 마신 방에 대고 다시 부르는 셈이다.
//   ★구조를 바꾸는 쪽(축사를 선창 앞으로)은 사장님 결정으로 올려 뒀고 아직 답을 못 받았다.
//     그래서 여기서는 «겹치는 한 줄만» 뺀다 — 선창은 나레이션이 이미 했다.
//     어느 쪽으로 결정되든 이 줄은 빼는 것이 맞다(축사가 앞으로 가면 선창을 예고할 필요가 없고,
//     뒤에 남으면 선창이 두 번이 된다). 구조 변경은 그대로 대기다.
//   ★앞줄 「오늘 같은 얼굴을 앞으로도 자주 보고 싶습니다」가 축사의 닫는 말로 충분하다.
//
// ★재녹음: 이겸 1클립(14_tribute) + 규민 1클립(15_toast). 27은 아직 녹음 전이라 0이다.

import fs from 'node:fs';
const ROOT = new URL('..', import.meta.url).pathname;
const F = 'docs/plans/식순연구/배역_예시_대사.txt';
let s = fs.readFileSync(ROOT + F, 'utf8');
let bad = 0;
const sub = (o, n) => {
  const c = s.split(o).length - 1;
  if (c !== 1) { console.log(`  ✗ "${o.slice(0, 34)}…" ${c}건 (1 기대)`); bad++; return; }
  s = s.replace(o, n); console.log(`  ✓ ${n || '(삭제)'}`);
};

console.log('\n① 어머니를 사진에서 비운다 — 세 줄');
sub('아버지가 저를 업고 계셨고, 뒤에서 어머니가 웃고 계셨습니다.', '아버지가 저를 업고 계셨습니다.');
sub('그 나이에 두 분은 저를 업고 다니셨더군요.', '그 나이에 아버지는 저를 업고 다니셨더군요.');
sub('저는 사진 속 두 분이 원래 어른인 줄 알았습니다.', '저는 사진 속 아버지가 원래 어른인 줄 알았습니다.');

console.log('\n② 축배 — 나레이션이 이미 한 선창을 축사가 또 한다');
sub('오늘 같은 얼굴을 앞으로도 자주 보고 싶습니다.\n자, 다 같이 잔 들겠습니다.\n', '오늘 같은 얼굴을 앞으로도 자주 보고 싶습니다.\n');

if (bad) { console.log(`\n★${bad}자리 어긋나 아무것도 쓰지 않았다.`); process.exit(2); }
fs.writeFileSync(ROOT + F, s);
console.log('\n[FRAME_OUT] 반영.');
