// 아버지는 자식에게 반말로, 아들딸 편지는 한 쌍으로 [SPEECH_LEVEL] [SON_DAUGHTER]
//
//   node scripts/apply-son-daughter.mjs [--write]
//
// ★왜 — 2026-09-12 사장님: *"아버지 존대하는거 조금 어색해 적절하게 개선해주고
//   아들딸 컵셉에 맞춰 부모님편지도 개선"*
//
// ★★[SPEECH_LEVEL — 아버님 덕담의 말단계가 네 번 갈아탔다]
//   실측: 습니다(2~9) → 반말(10~13) → 습니다(14~15) → 반말(16). 한 사람 안에서 왕복 네 번이다.
//   「서준아, 하윤아」로 부르고 「이거 쓰는 데 한 달 걸렸습니다」로 받는 그 이음매가 제일 크게 걸린다 —
//   자식을 이름으로 부르고 곧바로 하객에게 보고하는 꼴이라, 누구에게 말하는지가 한 줄마다 바뀐다.
//   ★고친 방향은 «존대로 통일»이 아니라 «반말로 통일»이다. 이 클립은 처음부터 끝까지
//     자식 둘에게 하는 말이고(호명으로 열어 「잘 살아라」로 닫는다), 하객은 «엿듣는» 쪽이다.
//     나레이션이 그 뒤에 「방금 그 말은, 오늘 이 자리에 있던 사람들만 들었습니다」라고 받는다 —
//     반말로 통일하면 그 문장이 비로소 사실이 된다. 존대로 올리면 하객에게 한 연설이 돼 그 줄이 거짓이 된다.
//   ★어머님은 «일부러» 다르게 둔다 — 존대로 하객에게 이야기하다 마지막 한 번만 딸에게 반말로 돈다.
//     말단계 왕복이 아니라 «단 한 번의 전환»이라 흔들리지 않고, 두 분의 목소리가 구별된다.
//     둘을 같은 말단계로 맞추지 말 것. 그러면 부모가 한 사람이 된다.
//   ★「저는 그날 저 사람이 어떤 사람인지 알았습니다」는 「아버지는 그날 알았다」로 줄였다 —
//     바로 뒤 두 줄(말로 하는 사람 / 그냥 하는 사람)이 그 답을 이미 말한다. 미리 요약하지 않는다.
//
// ★★[SON_DAUGHTER — 부모님께 드리는 말이 딸 것만 편지였다]
//   딸(10 letter-parent)은 13문장인데 아들(14 tribute)은 9문장이었고, 구조가 달랐다.
//   딸: 호명 → 못 한 말 → 장면 → 그때 몰랐던 것 → 지금 아는 것 → 고맙습니다 → 착지
//   아들: 호명 → 장면 → 나이 계산 → 착지.  «몰랐던 것 → 아는 것» 한 박자가 통째로 빠져 있었다.
//   그래서 아들에게 그 두 줄을 넣어 «짝»을 만들었다:
//     딸  「그 밤에 무슨 얘기를 하셨는지는 아직도 모릅니다 / 쉬운 밤이 아니었다는 건 이제 압니다」
//     아들「사진 속 두 분이 원래 어른인 줄 알았습니다 / 그 얼굴도 버티는 중이었다는 걸 이제 압니다」
//   ★같은 것을 따로 알아본다 — CROSS_ECHO(신랑↔어머님)와 같은 장치를 아들↔딸로 한 번 더 건다.
//     둘은 상의한 적이 없고, 하객만 둘을 다 듣는다.
//   ★「버티는 중」은 아들 자신의 「저 하나도 버거운데」를 되받는다(LETTER_COST). 아버지의 옛 얼굴에서
//     지금 자기 상태를 알아보는 것이라, 비유가 아니라 관찰이다.
//   ★말단계로 아들딸을 가른다 — 딸은 「엄마, 아빠」 + 해요체, 아들은 「어머니, 아버지」 + 합쇼체.
//     실제로 갈리는 방식이고, 두 편지가 나란히 놓였을 때 목소리가 섞이지 않는다.
//     ★딸 편지 뒷단의 -습니다체는 «사고가 아니라 전환»이다 — 회상(요체)에서 약속(습니다체)으로
//       허리를 펴는 자리다. 사장님이 살리라 한 「낳아주셔서, 키워주셔서, 참아주셔서 고맙습니다」가
//       그 전환 위에 얹힌다. 앞단을 습니다체로 올려 «통일»하지 말 것.
//
// ★★[HONORIFIC — 아버지에게 비존대 서술어가 붙어 있었다]
//   「그때 아버지가 지금 제 나이였습니다」 — 주어가 아버지인데 서술어가 평대다(「-였-」).
//   아들이 아버지 앞에서 읽는 문장이라 이건 문체가 아니라 «틀린 말»이다. → 「제 나이셨습니다」.
//   「뒤에서 어머니가 웃고 계셨어요」의 요체 한 줄도 합쇼체로 맞췄다(이 클립의 유일한 이탈이었다).
//
// ★[안 건드린 것] 「저 하나도 버거운데」(LETTER_COST · 말끝을 흐리는 고백) ·
//   「오늘부터 둘이 갑니다」 · 「다음에 갈 때도 빈손으로 가겠습니다」(LETTER_LAND) ·
//   「낳아주셔서, 키워주셔서, 참아주셔서 고맙습니다」(사장님 복원 지시) ·
//   어머님 전체(PEAK_ONE 정점) · 「하윤아, 너는 앞쪽이지」(BLESS_TURN).
//
// ★종료 코드 0 다 맞음 · 1 자리를 못 찾음
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const WRITE = process.argv.includes('--write');
const CAST = path.join(ROOT, 'docs/plans/식순연구/배역_예시_대사.txt');

const NEW = [
  ['10', `엄마, 아빠.
스물아홉 해 동안 고맙다는 말을 제대로 한 적이 없어요.
스물넷에 회사를 그만두겠다고 했던 날 기억하세요?
저녁을 먹고 제 방에 들어갔는데, 거실에서 두 분 목소리가 늦게까지 났어요.
무슨 말씀을 하시는지는 안 들렸어요.
다음 날 아침에 아빠가 밥 먹다가, 해 보라고 하셨어요.
엄마는 아무 말씀도 없이 제 국그릇에 고기를 덜어 주셨고요.
저는 그때 허락받았다고만 생각했어요.
그 밤에 두 분이 무슨 얘기를 하셨는지는 아직도 모릅니다.
쉬운 밤이 아니었다는 건 이제 압니다.
낳아주셔서, 키워주셔서, 참아주셔서 고맙습니다.
오늘부터 제 이름 옆에 한 사람이 더 생기지만, 두 분 딸인 것은 그대로입니다.
다음에 갈 때도 빈손으로 가겠습니다.`],
  ['12', `서준아, 하윤아.
이거 쓰는 데 한 달 걸렸다.
그래도 길게는 안 한다.
작년 겨울에 우리 집 보일러가 고장 났다.
날이 추워서 하윤이한테만 말했는데, 그 주 토요일에 서준이가 왔더라.
두 시간을 만지더니 고쳐 놓고, 밥도 안 먹고 갔다.
아버지는 그날 알았다.
말로 하는 사람이 있고, 그냥 하는 사람이 있다.
서준아, 너는 뒤쪽이더라.
하윤아, 너는 앞쪽이지.
살다 보면 서로 미운 날이 온다.
그때 먼저 말을 거는 건 아마 네가 할 거다.
지는 게 아니다. 아버지는 그걸 알기까지 오래 걸렸다.
하윤이 손을 스물아홉 해 잡고 걸었다.
그게 참 좋았다.
잘 살아라.`],
  ['14', `어머니, 아버지.
얼마 전에 집에서 오래된 사진을 봤습니다.
아버지가 저를 업고 계셨고, 뒤에서 어머니가 웃고 계셨습니다.
사진 뒤에 날짜가 적혀 있길래 세어 봤습니다.
그때 아버지가 지금 제 나이셨습니다.
저는 아직 저 하나도 버거운데.
그 나이에 두 분은 저를 업고 다니셨더군요.
저는 사진 속 두 분이 원래 어른인 줄 알았습니다.
그 얼굴도 버티는 중이었다는 걸 이제 압니다.
앞으로는 자주 찾아뵙겠습니다.
오늘부터 둘이 갑니다.`],
];

const lines = fs.readFileSync(CAST, 'utf8').split('\n');
const at = new Map();
lines.forEach((l, i) => { const m = /^\[(\d+)\]/.exec(l); if (m) at.set(m[1], i); });
const syl = (s) => (s.match(/[가-힣]/g) || []).length;
/* [LAND_VOCATIVE] 호명(「하윤아.」)은 문장이 아니라 부름이다 — 건너뛰고 그 앞과 잰다. */
const isCall = (s) => syl(s) < 6 && /[아야]\.$/.test(s.trim());
let bad = 0;
const plan = [];
for (const [no, text] of NEW) {
  const h = at.get(no);
  if (h === undefined) { console.log(`✗ [${no}] 머리를 못 찾았다`); bad++; continue; }
  let e = h + 1;
  while (e < lines.length && lines[e].trim()) e++;
  const neu = text.split('\n').map((s) => s.trim()).filter(Boolean);
  plan.push({ no, h, e, neu, old: lines.slice(h + 1, e) });
}

/* ★말단계 자가검사 — 이 커밋의 «본론»이라 눈으로 보지 않고 센다.
   한 블록 안에서 평대 종결과 존대 종결이 섞이면 그 줄을 전부 찍는다.
   ★어머님(13)은 검사에서 뺀다 — 마지막 한 줄만 딸에게 도는 것이 설계다(위 주석). */
/* ★[POLITE_NIDA] 「압니다·갑니다·모릅니다」를 놓치면 안 된다 — 한글은 미리 합쳐진 글자라
   「ㅂ니다」로는 안 잡힌다. 「니다」로 끝나는지만 본다. 「요」도 마찬가지로 어미를 열거하지 않는다. */
const POLITE = /(니다|요|십시오)[.?!]?$/;
const PLAIN = /(다|지|라|어|야|까|네|군|걸|더라)[.?!]?$/;
const levelOf = (s) => (POLITE.test(s.trim()) ? '존대' : PLAIN.test(s.trim()) ? '평대' : '?');
for (const p of plan) {
  const body = p.neu.filter((s) => !isCall(s) && !/^[가-힣]+, [가-힣]+\.$/.test(s));
  const lv = [...new Set(body.map(levelOf).filter((x) => x !== '?'))];
  const last = syl(p.neu[p.neu.length - 1]);
  let pi = p.neu.length - 2; while (pi > 0 && isCall(p.neu[pi])) pi--;
  const prev = syl(p.neu[pi] ?? '');
  const who = lines[p.h].split('·')[1]?.trim() ?? '';
  const sec = (p.neu.reduce((a, s) => a + syl(s), 0) / 406 * 60).toFixed(0);
  console.log(`  [${p.no}] ${who.padEnd(5)} ${p.old.length}→${p.neu.length}문장 · 약 ${sec}초 · 말단계 ${lv.join('+').padEnd(5)} ${lv.length === 1 ? 'ok' : '★섞임'} · 끝 ${last}(앞 ${prev}) ${last < prev ? '착지 ok' : '★긺'}`);
  if (lv.length !== 1) { p.neu.forEach((s) => console.log(`       ${levelOf(s)} ${s}`)); bad++; }
}
if (bad) { console.log('\n맞지 않는 것이 있다 — 아무것도 쓰지 않는다.'); process.exit(1); }
if (!WRITE) { console.log('\n(안 씀 · --write 로 실제 반영)'); process.exit(0); }
const out = [];
let i = 0;
for (const p of plan.sort((a, b) => a.h - b.h)) { out.push(...lines.slice(i, p.h + 1), ...p.neu); i = p.e; }
out.push(...lines.slice(i));
fs.writeFileSync(CAST, out.join('\n'));
console.log(`\n반영함 · ${plan.length}클립`);
