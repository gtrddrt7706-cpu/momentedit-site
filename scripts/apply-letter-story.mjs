//   나는 목격담을 넣었지만 «한 줄»로 요약해 놓았다. 요약은 장면이 아니다.
//
// ★★[고친 방식 — 한 일화를 처음·중간·끝으로 끌고 간다]
//   어머님은 「하윤이가 아프다고 말하지 않는다」를 «고3 어느 날»로 펼쳤다.
//     양호실에 누워 있는 것을 보고 어머니가 무서워지는 데까지 간다. 그 두려움이 곧 사위에게 넘기는 이유가 된다.
//     ★부탁이 이야기 뒤에 오면 부탁이 아니라 «인수인계»가 된다 — 그래서 「부탁합니다」를 안 쓴다.
//   아버님은 보일러를 «토요일 두 시간»으로 펼치고, 대구 한 쌍으로 사람됨을 정리한 뒤 손으로 닫는다.
//   신랑·신부 서약도 요약을 장면으로 바꿨다 — 「설거지를 오래 해」 → 그 주에 그릇이 반짝였다.
//
// ★길이 — 사장님이 「조금 길어도 괜찮다」고 했다. 덕담이 12~13 → 16~17문장(약 50초)이 된다.
//   조사에서 하객 불만은 «진부함»보다 «길이»가 압도적이었지만, 그 기준은 3~5분이다. 50초는 그 안이다.
//
// ★지킨 것 — CROSS_ECHO(신랑 「한 번은 더 물을게」 ↔ 어머님 「한 번만 더 물어봐 주세요」)는
//   그대로다. 오히려 어머니 쪽에 이야기가 붙어 겹침이 더 세졌다.
//   착지(LETTER_LAND)·고백(LETTER_COST)·격식(LETTER_FORMAL)도 전부 유지한다.
